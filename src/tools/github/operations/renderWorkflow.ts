import { readFile } from "node:fs/promises";

import {
  isMap,
  isScalar,
  isSeq,
  parseDocument,
  type Document,
  type YAMLMap,
} from "yaml";

import { isString } from "@auaust/toolkit/isString";

import { resolveDataFile } from "#foundation/data/index";
import { workflowTemplates } from "#tools/github/constants";
import type { WorkflowSetName } from "#tools/github/types/WorkflowSetName";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";

const testJob = "test";

const testCommand = "pnpm run ci:test";

function readMap(node: unknown, location: string): YAMLMap {
  if (!isMap(node)) {
    throw new Error(`The workflow template's ${location} must be a mapping`);
  }

  return node;
}

function insertBefore(
  document: Document,
  map: YAMLMap,
  before: string,
  { key, value, spaced }: { key: string; value: unknown; spaced: boolean },
): void {
  const pair = document.createPair(key, value);

  if (isScalar(pair.key)) {
    pair.key.spaceBefore = spaced;
  }

  const index = map.items.findIndex((item) => {
    return isScalar(item.key) && item.key.value === before;
  });

  map.items.splice(index === -1 ? map.items.length : index, 0, pair);
}

function listJobSteps(job: YAMLMap, name: string): readonly YAMLMap[] {
  const steps = job.get("steps");

  if (!isSeq(steps)) {
    throw new Error(`The workflow template's job ${name} must list its steps`);
  }

  return steps.items.map((step) => {
    return readMap(step, `job ${name} step`);
  });
}

function listSteps(jobs: YAMLMap): readonly YAMLMap[] {
  return jobs.items.flatMap(({ key, value }) => {
    const name = String(key);

    return listJobSteps(readMap(value, `job ${name}`), name);
  });
}

function shardTests(document: Document, jobs: YAMLMap, shards: number): void {
  if (shards === 1 || !jobs.has(testJob)) {
    return;
  }

  const job = readMap(jobs.get(testJob), `job ${testJob}`);

  job.set("name", `Test (\${{ matrix.shard }}/${shards})`);

  insertBefore(document, job, "runs-on", {
    key: "strategy",
    value: {
      matrix: {
        shard: Array.from({ length: shards }, (_, index) => index + 1),
      },
    },
    spaced: true,
  });

  for (const step of listJobSteps(job, testJob)) {
    if (step.get("run") === testCommand) {
      step.set(
        "run",
        `${testCommand} --shard=\${{ matrix.shard }}/\${{ strategy.job-total }}`,
      );
    }
  }
}

// @debt the pnpm lockfile name repeats `tools/pnpm`'s `pnpm-lock.yaml` resource instead of reading its location
function relocate(
  document: Document,
  steps: readonly YAMLMap[],
  directory: Directory,
): void {
  insertBefore(document, readMap(document.contents, "root"), "jobs", {
    key: "defaults",
    value: {
      run: { "working-directory": directory },
    },
    spaced: true,
  });

  for (const step of steps) {
    const options = step.get("with");

    if (!isMap(options)) {
      continue;
    }

    const nodeVersionFile = options.get("node-version-file");

    if (isString(nodeVersionFile)) {
      options.set("node-version-file", `${directory}/${nodeVersionFile}`);
    }

    if (options.get("cache") === "pnpm") {
      options.set("cache-dependency-path", `${directory}/pnpm-lock.yaml`);
    }

    if (options.has("publish-script")) {
      insertBefore(document, options, "publish-script", {
        key: "cwd",
        value: directory,
        spaced: false,
      });
    }
  }
}

export async function renderWorkflow(
  name: WorkflowSetName,
  file: File,
  {
    directory,
    testShards,
  }: {
    directory: Directory;
    testShards: number;
  },
): Promise<string> {
  const template = resolveDataFile(`${workflowTemplates}/${name}/${file}`);

  const document = parseDocument(await readFile(template, "utf-8"));

  if (document.errors.length > 0) {
    throw new Error(`Cannot read the ${name} workflow template ${file}`, {
      cause: document.errors[0],
    });
  }

  const jobs = readMap(document.get("jobs"), "jobs");

  shardTests(document, jobs, testShards);

  if (directory !== ".") {
    relocate(document, listSteps(jobs), directory);
  }

  return `# Generated by \`engrenage sync workflows\` from the ${name} workflows. Edits are overwritten on the next sync.\n\n${document.toString({ lineWidth: 0 })}`;
}
