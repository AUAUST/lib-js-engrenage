import { readFileSync } from "node:fs";

import { resolveDataFile } from "#foundation/data/operations/resolveDataFile";
import { workflowTemplates } from "#tools/github/constants";
import type { WorkflowSetName } from "#tools/github/types/WorkflowSetName";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";

// @debt relocating a nested project's workflows by string substitution on the templates silently stops matching when a template changes; template the YAML instead
function relocate(template: string, directory: Directory): string {
  return template
    .replace(/^jobs:/m, () => {
      return `defaults:\n  run:\n    working-directory: ${directory}\n\njobs:`;
    })
    .replaceAll(/^(\s*)node-version-file: (.+)$/gm, (_line, indent, file) => {
      return `${indent}node-version-file: ${directory}/${file}`;
    })
    .replaceAll(/^(\s*)cache: "pnpm"$/gm, (line, indent) => {
      return `${line}\n${indent}cache-dependency-path: ${directory}/pnpm-lock.yaml`;
    })
    .replaceAll(/^(\s*)publish-script: .+$/gm, (line, indent) => {
      return `${indent}cwd: ${directory}\n${line}`;
    });
}

export function renderWorkflow(
  name: WorkflowSetName,
  file: File,
  directory: Directory = ".",
): string {
  const template = resolveDataFile(`${workflowTemplates}/${name}/${file}`);
  const content = readFileSync(template, "utf-8");

  return `# Generated by \`engrenage sync workflows\` from the ${name} workflows. Edits are overwritten on the next sync.\n\n${directory === "." ? content : relocate(content, directory)}`;
}
