import { posix } from "node:path";

import { engrenage } from "#constants";
import {
  claudeAgentsDir,
  claudeSkillsDir,
} from "#tools/agents/claude/constants";
import { codexAgentsDir, codexSkillsDir } from "#tools/agents/codex/constants";
import { getSkillDefinitions } from "#tools/agents/operations/getSkillDefinitions";
import { listFormerReferences } from "#tools/agents/utils/listFormerReferences";
import type { Filesystem } from "#foundation/filesystem/index";
import type { Extension } from "#project/config/index";
import type { ResolvedAgents } from "#tools/agents/types/ResolvedAgents";
import type { SkillDefinition } from "#tools/agents/types/SkillDefinition";
import type { BlockFillers } from "#types/BlockFillers";
import type { Directory } from "#types/Directory";

const skillReferencePrefix = `${engrenage}/agents/skills/`;

// @debt the Codex provenance line is parsed here and built in `createCodexAgentProfiles`; one owner of its format would keep them aligned
const codexProvenancePrefix = "# Generated by engrenage from ";

function findReferences(content: string): readonly string[] {
  return [...content.matchAll(/<!-- @reference (\S+) -->/g)].map((match) => {
    return match[1] ?? "";
  });
}

const generatedSkillFiles = ["SKILL.md", "agents/openai.yaml"];

async function removeSkillFiles(filesystem: Filesystem, directory: Directory) {
  for (const file of generatedSkillFiles) {
    await filesystem.remove(`${directory}/${file}`);
  }
}

async function moveSkillDirectory(
  filesystem: Filesystem,
  from: Directory,
  to: Directory,
  rewrite: (content: string) => string,
) {
  if (await filesystem.isDirectory(to)) {
    return removeSkillFiles(filesystem, from);
  }

  for (const file of await filesystem.list(from)) {
    const content = await filesystem.read(file);

    if (content !== undefined) {
      await filesystem.write(
        `${to}${file.slice(from.length)}`,
        rewrite(content),
      );
    }

    await filesystem.remove(file);
  }
}

export async function migrateSkillFiles(config: {
  filesystem: Filesystem;
  agents: ResolvedAgents;
  extensions: readonly Extension[];
  fillers: BlockFillers;
}) {
  const { filesystem } = config;

  const definitions = await getSkillDefinitions(config);

  const owners = new Map<string, SkillDefinition>();

  for (const definition of definitions) {
    owners.set(definition.reference, definition);

    for (const former of listFormerReferences(definition)) {
      owners.set(former, definition);
    }
  }

  function findOwned(content: string) {
    return findReferences(content).find((reference) => {
      return (
        owners.has(reference) || reference.startsWith(skillReferencePrefix)
      );
    });
  }

  function rewriteTo(definition: SkillDefinition | undefined) {
    return (content: string) => {
      return definition === undefined
        ? content
        : listFormerReferences(definition).reduce((current, former) => {
            return current
              .split(`<!-- @reference ${former} -->`)
              .join(`<!-- @reference ${definition.reference} -->`);
          }, content);
    };
  }

  for (const directory of [claudeSkillsDir, codexSkillsDir]) {
    for (const file of await filesystem.glob(`${directory}/*/SKILL.md`)) {
      const reference = findOwned((await filesystem.read(file)) ?? "");

      if (reference === undefined) {
        continue;
      }

      const definition = owners.get(reference);
      const from = posix.dirname(file);

      if (definition === undefined) {
        await removeSkillFiles(filesystem, from);
      } else if (from !== `${directory}/${definition.name}`) {
        await moveSkillDirectory(
          filesystem,
          from,
          `${directory}/${definition.name}`,
          rewriteTo(definition),
        );
      }
    }
  }

  for (const file of await filesystem.glob(`${claudeAgentsDir}/*.md`)) {
    const content = (await filesystem.read(file)) ?? "";
    const reference = findOwned(content);

    if (reference === undefined) {
      continue;
    }

    const definition = owners.get(reference);

    const target = definition?.agent === undefined
      ? undefined
      : `${claudeAgentsDir}/${definition.agent.name}.md`;

    if (file === target) {
      continue;
    }

    if (target !== undefined && !(await filesystem.exists(target))) {
      await filesystem.write(target, rewriteTo(definition)(content));
    }

    await filesystem.remove(file);
  }

  for (const file of await filesystem.glob(`${codexAgentsDir}/*.toml`)) {
    const content = (await filesystem.read(file)) ?? "";

    if (!content.startsWith(codexProvenancePrefix)) {
      continue;
    }

    const reference = content
      .slice(codexProvenancePrefix.length, content.indexOf("\n"))
      .trim();

    const isCurrent = definitions.some((definition) => {
      return definition.reference === reference;
    });

    if (
      !isCurrent &&
      (owners.has(reference) || reference.startsWith(skillReferencePrefix))
    ) {
      await filesystem.remove(file);
    }
  }

  const renames = definitions.flatMap((definition) => {
    return listFormerReferences(definition).map((former) => {
      return {
        from: `<!-- @reference ${former} -->`,
        to: `<!-- @reference ${definition.reference} -->`,
      };
    });
  });

  if (renames.length === 0) {
    return;
  }

  for (const file of await filesystem.glob(config.agents.instructionFiles)) {
    const content = await filesystem.read(file);

    if (content === undefined) {
      continue;
    }

    const rewritten = renames.reduce((current, { from, to }) => {
      return current.split(from).join(to);
    }, content);

    if (rewritten !== content) {
      await filesystem.write(file, rewritten);
    }
  }
}
