import { stringifyTOML } from "confbox/toml";

import { codexAgentsDir } from "#tools/agents/codex/constants";
import type { SkillDefinition } from "#tools/agents/types/SkillDefinition";

export function createCodexAgentProfiles({
  agent,
  reference,
  body,
}: {
  agent: NonNullable<SkillDefinition["agent"]>;
  reference: string;
  body: string;
}) {
  const variants = agent.gate === true
    ? ([undefined, "low", "high"] as const)
    : [undefined];

  return variants.map((variant) => {
    const name = variant === undefined
      ? agent.name
      : `${agent.name}_${variant}`;

    const effort = variant ?? agent.effort;
    const provenance = `# Generated by engrenage from ${reference}\n`;

    const bootstrap = "Read and follow ./AGENTS.md and ./AGENTS.override.md before working. Read every All files rule in its rule mapping, then every matching scoped rule before editing.\n\n";

    return {
      name,
      role: agent.name,
      effort,
      gate: agent.gate === true,
      file: `${codexAgentsDir}/${name}.toml`,
      provenance,
      content: (
        provenance +
        stringifyTOML({
          name,
          description: agent.description,
          ...(effort !== undefined && { model_reasoning_effort: effort }),
          developer_instructions: bootstrap + body,
        })
      ),
    };
  });
}
