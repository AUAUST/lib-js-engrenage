import { parseDocument } from "yaml";

import { codexAgentsDir, codexSkillsDir } from "#tools/agents/codex/constants";
import { createCodexAgentProfiles } from "#tools/agents/codex/operations/createCodexAgentProfiles";
import { listFormerReferences } from "#tools/agents/utils/listFormerReferences";
import type { Filesystem } from "#foundation/filesystem/index";
import type { SkillDefinition } from "#tools/agents/types/SkillDefinition";

export async function syncCodexSkill(
  filesystem: Filesystem,
  template: SkillDefinition,
) {
  const { name, reference, invocation, agent, body } = template;

  const profiles = agent === undefined
    ? []
    : createCodexAgentProfiles({
        agent,
        reference,
        body,
      });

  const skill = await filesystem.read(`${codexSkillsDir}/${name}/SKILL.md`);

  if (!skill?.includes(`<!-- @reference ${reference} -->`)) {
    return;
  }

  const policyFile = `${codexSkillsDir}/${name}/agents/openai.yaml`;

  const policy = parseDocument((await filesystem.read(policyFile)) ?? "");

  if (policy.errors.length > 0) {
    throw new Error(`Invalid Codex skill metadata ${policyFile}`, {
      cause: policy.errors[0],
    });
  }

  policy.setIn(
    ["policy", "allow_implicit_invocation"],
    invocation === "implicit",
  );

  await filesystem.write(policyFile, policy.toString());

  // @debt The provenance line is built here and in `createCodexAgentProfiles`, and profile ownership is judged here and in `checkAgents`, which ignores former provenances; one owner of the provenance and its ownership test would keep them aligned.
  const formerProvenances = listFormerReferences(template).map((former) => {
    return `# Generated by engrenage from ${former}\n`;
  });

  for (const profile of profiles) {
    const current = await filesystem.read(profile.file);

    const isOwned = (
      current === undefined ||
      [profile.provenance, ...formerProvenances].some((provenance) => {
        return current.startsWith(provenance);
      })
    );

    if (!isOwned) {
      throw new Error(`Unowned Codex agent profile ${profile.file}`);
    }

    await filesystem.write(profile.file, profile.content);
  }

  for (const file of await filesystem.glob(`${codexAgentsDir}/*.toml`)) {
    if (profiles.some((profile) => profile.file === file)) {
      continue;
    }

    const content = await filesystem.read(file);

    if (content?.startsWith(`# Generated by engrenage from ${reference}\n`)) {
      await filesystem.remove(file);
    }
  }
}
