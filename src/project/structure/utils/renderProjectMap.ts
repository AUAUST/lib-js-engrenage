import { entries, values } from "@auaust/toolkit/object";

import {
  dataEnvironment,
  importCategories,
  importRelations,
  sourceEnvironment,
} from "#project/structure/constants";
import { renderProjectMapRoles } from "#project/structure/utils/renderProjectMapRoles";
import type { EnvironmentEntry } from "#project/environments/index";
import type { ImportCategory } from "#project/structure/types/ImportCategory";
import type { ImportGrants } from "#project/structure/types/ImportGrants";
import type { ResolvedRoles } from "#project/structure/types/ResolvedRoles";
import type { ResolvedStructure } from "#project/structure/types/ResolvedStructure";
import type { TestVariant } from "#project/structure/types/TestVariant";
import type { Directory } from "#types/Directory";
import type { Globs } from "#types/Globs";

function code(value: string): string {
  return `\`${value}\``;
}

function list(values: readonly string[]): string {
  return values.map(code).join(", ");
}

function renderCell(
  name: string,
  category: ImportCategory,
  grants: ImportGrants,
): string {
  const forbidden = category === dataEnvironment
    ? grants.data.includes(name)
    : grants.environments[name]?.includes(category) === true;

  if (forbidden) {
    return "never";
  }

  if (name === "tests") {
    const variants = values(grants.variants).map((categories) => {
      return categories?.includes(category) === true;
    });

    if (variants.some(Boolean) && !variants.every(Boolean)) {
      return "per variant";
    }

    if (variants.some(Boolean)) {
      return "never";
    }
  }

  return "yes";
}

function listCategories(
  environments: readonly EnvironmentEntry[],
): readonly (readonly [ImportCategory, string])[] {
  return [
    ["public-entries", importCategories["public-entries"]],
    ["internal-aliases", importCategories["internal-aliases"]],
    ...environments
      .filter(({ name }) => name !== sourceEnvironment)
      .map(({ name, title }) => [name, title] as const),
    ["dist-artefacts", importCategories["dist-artefacts"]],
  ];
}

export function renderProjectMap({
  structure,
  environments,
  grants,
  patterns,
  roles,
  directory,
}: {
  structure: ResolvedStructure;
  environments: readonly EnvironmentEntry[];
  grants: ImportGrants;
  patterns: { plain: Globs; source: Globs; dist: Globs };
  roles: Readonly<Partial<Record<string, ResolvedRoles>>>;
  directory: Directory;
}): string {
  const mapped = entries(structure)
    .filter(([, environment]) => environment !== undefined)
    .map(([name]) => name);

  const categories = listCategories(environments);

  const columns = categories.map(([category]) => category);

  const variants: readonly TestVariant[] = ["plain", "src", "dist"];

  const variantRows = variants.map((variant) => {
    const forbidden = grants.variants[variant] ?? [];
    const allowed = columns.filter((category) => !forbidden.includes(category));

    const globs = {
      plain: patterns.plain,
      src: patterns.source,
      dist: patterns.dist,
    }[variant];

    const against = {
      plain: "source and dist",
      src: "source",
      dist: "dist",
    }[variant];

    return `| ${list(globs)} | ${against} | ${list(allowed)} | ${list(forbidden)} |`;
  });

  return [
    "# Project map",
    "",
    "Generated by `engrenage sync agents` from the project structure. Do not edit.",
    "",
    "## Notation",
    "",
    "Trees: `name*` public domain, `{…}` sub-domains, `#alias/…` import alias, `[isolated]` peers never import each other, `[domains]` every child directory is a domain.",
    "",
    "| Relation | A domain may import |",
    "| --- | --- |",
    ...entries(importRelations)
      .filter(([relation]) => relation !== "workspace")
      .map(([relation, meaning]) => `| ${code(relation)} | ${meaning} |`),
    "",
    "## Environments",
    "",
    `The matrix states environment grants; domain and role boundaries still apply. No importer but its environment's root \`executable.ts\` may import a root index or entry file of ${list(grants.elements)}. ${list(grants.consumers)} import \`src\` only through a domain's \`index.ts\`, \`entry.ts\` and public roles.`,
    "",
    "| Category | Meaning |",
    "| --- | --- |",
    ...categories.map(([category, meaning]) => {
      return `| ${code(category)} | ${meaning} |`;
    }),
    "",
    `| from / to | ${columns.join(" | ")} | map |`,
    `| --- |${columns.map(() => " --- |").join("")} --- |`,
    ...mapped.map((name) => {
      const cells = columns.map((category) => {
        return renderCell(name, category, grants);
      });

      return `| ${code(name)} | ${cells.join(" | ")} | ${code(`${directory}/${name}.md`)} |`;
    }),
    ...(grants.published
      ? [
          "",
          "## Test files",
          "",
          "| Files | Runs against | May import | Never |",
          "| --- | --- | --- | --- |",
          ...variantRows,
        ]
      : []),
    ...(grants.workspaces.size === 0
      ? []
      : [
          "",
          "## Workspaces",
          "",
          importRelations.workspace,
          "Root src never imports a workspace.",
          "",
          ...[...grants.workspaces].map(([path, dependencies]) => {
            return `- ${code(path)}: ${dependencies.length === 0 ? "no workspace dependencies" : list(dependencies)}`;
          }),
        ]),
    ...renderProjectMapRoles(structure, roles),
  ].join("\n");
}
