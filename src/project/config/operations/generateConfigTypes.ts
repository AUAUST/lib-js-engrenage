import {
  toJsonSchema,
  type JsonSchema,
  type OverrideSchemaContext,
} from "@valibot/to-json-schema";
import { compile } from "json-schema-to-typescript-lite";
import type { BaseIssue, BaseSchema } from "valibot";

import { isBoolean } from "@auaust/toolkit/isBoolean";
import { mappedValues } from "@auaust/toolkit/mappedValues";
import { keys } from "@auaust/toolkit/object";

import { configSchema } from "#project/config/config/schemas/configSchema";
import { globsSchema } from "#project/config/config/schemas/values/globsSchema";
import { presetListSchema } from "#project/config/config/schemas/values/presetListSchema";
import type { ResolvedConfig } from "#project/config/types/ResolvedConfig";
import type { File } from "#types/File";

const configFile: File = "src/project/config/types/ConfigInput.ts";

const generatedHeader =
  "// Generated by `pnpm support codegen config`. Do not edit.\n";

const imports = [
  'import type { GlobalsFactory } from "#project/config/types/GlobalsFactory";',
  'import type { ListOption } from "#project/config/types/ListOption";',
  'import type { ManagedListOption } from "#project/config/types/ManagedListOption";',
  'import type { Preset } from "#project/presets/types/Preset";',
  'import type { Presets } from "#project/presets/types/Presets";',
  'import type { Glob } from "#types/Glob";',
  'import type { Globs } from "#types/Globs";',
];

type AnySchema = BaseSchema<unknown, unknown, BaseIssue<unknown>>;

interface UnionSchema {
  type: "union";
  options: readonly AnySchema[];
}

interface ObjectSchema {
  type: "strict_object";
  entries: Readonly<Record<string, AnySchema>>;
}

const adjustmentKeys = ["append", "exclude", "prepend"];

function isUnion(schema: AnySchema): schema is AnySchema & UnionSchema {
  return schema.type === "union";
}

function isAdjustment(schema: AnySchema): boolean {
  const { entries } = schema as AnySchema & Partial<ObjectSchema>;

  return (
    schema.type === "strict_object" &&
    entries !== undefined &&
    keys(entries).sort().join() === adjustmentKeys.join()
  );
}

function findListItem(schema: AnySchema): AnySchema | undefined {
  if (!isUnion(schema) || schema.options.length !== 2) {
    return;
  }

  const [items, adjustment] = schema.options;

  if (!isAdjustment(adjustment) || !isUnion(items)) {
    return;
  }

  return items.options[0];
}

function findManagedListItem(schema: AnySchema): AnySchema | undefined {
  if (!isUnion(schema) || schema.options.length !== 2) {
    return;
  }

  const [list, flag] = schema.options;

  return flag.type === "boolean" ? findListItem(list) : undefined;
}

function renderItem(schema: AnySchema): string {
  const { type, enum: values } = toJsonSchema(schema, {
    errorMode: "throw",
  }) as { type?: string; enum?: readonly string[] };

  if (type === "string" && values === undefined) {
    return "string";
  }

  if (values !== undefined) {
    return values.map((value) => JSON.stringify(value)).join(" | ");
  }

  throw new Error(
    `The list item of type ${schema.type} has no TypeScript form`,
  );
}

function optionsOf(schema: object): unknown {
  return "options" in schema ? schema.options : undefined;
}

const readonlyListTypes = new Map<unknown, string>([
  [optionsOf(presetListSchema), "Preset | Presets"],
  [optionsOf(globsSchema), "Glob | Globs"],
]);

function resolveType(schema: AnySchema): string | undefined {
  if (schema.type === "custom") {
    return "GlobalsFactory";
  }

  const readonlyList = readonlyListTypes.get(optionsOf(schema));

  if (readonlyList !== undefined) {
    return readonlyList;
  }

  const managed = findManagedListItem(schema);

  if (managed !== undefined) {
    return `ManagedListOption<${renderItem(managed)}>`;
  }

  const list = findListItem(schema);

  return list === undefined ? undefined : `ListOption<${renderItem(list)}>`;
}

function withType(schema: JsonSchema, tsType: string): JsonSchema {
  const typed = { ...schema, tsType };

  return typed;
}

function allowUndefined(
  { entries }: AnySchema & ObjectSchema,
  jsonSchema: JsonSchema,
): JsonSchema {
  const properties = mappedValues(
    jsonSchema.properties ?? {},
    (property, name): JsonSchema | boolean => {
      if (isBoolean(property) || entries[name]?.type !== "optional") {
        return property;
      }

      const { description, ...rest } = property;

      const wrapped: JsonSchema = {
        anyOf: [rest, withType(rest, "undefined")],
      };

      if (description !== undefined) {
        wrapped.description = description;
      }

      return wrapped;
    },
  );

  return { ...jsonSchema, properties };
}

function isObjectDefinition(definition: JsonSchema | boolean): boolean {
  return !isBoolean(definition) && definition.type === "object";
}

function placeObjectsLast(jsonSchema: JsonSchema): JsonSchema {
  const anyOf = [
    ...(jsonSchema.anyOf ?? []).filter((member) => !isObjectDefinition(member)),
    ...(jsonSchema.anyOf ?? []).filter((member) => isObjectDefinition(member)),
  ];

  return { ...jsonSchema, anyOf };
}

function overrideSchema({ valibotSchema, jsonSchema }: OverrideSchemaContext) {
  const tsType = resolveType(valibotSchema);

  if (tsType !== undefined) {
    return withType(jsonSchema, tsType);
  }

  if (valibotSchema.type === "union" && jsonSchema.anyOf !== undefined) {
    return placeObjectsLast(jsonSchema);
  }

  if (valibotSchema.type === "strict_object") {
    return allowUndefined(
      valibotSchema as AnySchema & ObjectSchema,
      jsonSchema,
    );
  }
}

export async function generateConfigTypes(config: ResolvedConfig) {
  const jsonSchema = toJsonSchema(configSchema, {
    errorMode: "ignore",
    typeMode: "input",
    overrideSchema,
  });

  // @debt the draft 07 JSON schema of valibot is asserted to the draft 04 type of json-schema-to-typescript-lite, which only differs by numeric exclusive bounds that configSchema does not use
  const document = jsonSchema as Parameters<typeof compile>[0];

  const declarations = await compile(document, "ConfigInput", {
    additionalProperties: false,
    unknownAny: true,
  });

  config.filesystem.write(
    configFile,
    [generatedHeader, ...imports, "", declarations].join("\n"),
  );
}
