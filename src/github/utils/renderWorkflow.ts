import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

import { workflowTemplates } from "#github/constants";
import type { WorkflowSetName } from "#github/types/WorkflowSetName";
import type { File } from "#types/File";

export function renderWorkflow(name: WorkflowSetName, file: File): string {
  const template = createRequire(import.meta.url).resolve(
    `${workflowTemplates}/${name}/${file}`,
  );

  return `# Generated by \`engrenage sync workflows\` from the ${name} workflows. Edits are overwritten on the next sync.\n\n${readFileSync(template, "utf-8")}`;
}
