import { readFileSync } from "node:fs";
import { createRequire } from "node:module";

import { every, find, includes, map } from "@auaust/primitive-kit/arrays";
import { hasOwn } from "@auaust/toolkit/object";

import {
  workflowsDirectory,
  workflowSetNames,
  workflowSets,
  workflowTemplates,
} from "#github/constants";
import { syncFiles } from "#utils/syncFiles";
import type { ResolvedConfig } from "#config/types/ResolvedConfig";
import type { WorkflowSetName } from "#github/types/WorkflowSetName";
import type { File } from "#types/File";
import type { SyncResults } from "#types/SyncResults";

function resolveWorkflowSet(
  config: ResolvedConfig,
): WorkflowSetName | undefined {
  const { workflows } = config.github;

  if (workflows !== undefined) {
    return workflows === false ? undefined : workflows;
  }

  return find(workflowSetNames, (name) => {
    return (
      includes(config.presets, name) &&
      every(workflowSets[name].requires, (dependency) => {
        return config.environment.hasDependency(dependency);
      })
    );
  });
}

function assertScripts(
  config: ResolvedConfig,
  name: WorkflowSetName,
  required: ReadonlyArray<string>,
) {
  const scripts = config.packageJson.optional.scripts ?? {};

  for (const script of required) {
    if (!hasOwn(scripts, script)) {
      throw new Error(
        `${config.packageJsonPath} does not declare the "${script}" script that the ${name} workflows run`,
      );
    }
  }
}

function readTemplate(name: WorkflowSetName, file: File): string {
  const template = createRequire(import.meta.url).resolve(
    `${workflowTemplates}/${name}/${file}`,
  );

  return `# Generated by \`engrenage sync workflows\` from the ${name} workflows. Edits are overwritten on the next sync.\n\n${readFileSync(template, "utf8")}`;
}

export function syncWorkflowFiles({
  config,
  check = false,
}: {
  config: ResolvedConfig;
  check?: boolean;
}): SyncResults {
  const name = resolveWorkflowSet(config);

  if (name === undefined) {
    return [];
  }

  const { files, scripts } = workflowSets[name];

  assertScripts(config, name, scripts);

  const syncs = map(files, (file) => {
    const content = readTemplate(name, file);

    return {
      file: `${workflowsDirectory}/${file}`,
      initial: content,
      update() {
        return content;
      },
    };
  });

  return syncFiles({
    root: config.root,
    files: syncs,
    check,
  });
}
