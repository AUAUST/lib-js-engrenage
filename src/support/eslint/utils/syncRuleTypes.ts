import { ruleSourcesDirectory } from "#support/eslint/constants/ruleSourcesDirectory";
import { rulesFile } from "#support/eslint/constants/rulesFile";
import { loadConfig } from "#config/utils/loadConfig";
import { createEslintConfig } from "#eslint/builders/createEslintConfig";
import type { Plugin } from "#eslint/types/Plugin";
import { normalizeRuleSchema } from "#support/eslint/utils/normalizeRuleSchema";
import { resolve } from "#support/filesystem/utils/resolve";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";
import { map } from "@auaust/primitive-kit/arrays";
import { toPascalCase } from "@auaust/primitive-kit/strings";
import { mappedValues } from "@auaust/toolkit/mappedValues";
import { entries, record } from "@auaust/toolkit/object";
import { flatConfigsToPlugins, pluginsToRulesDTS } from "eslint-typegen/core";
import { builtinRules } from "eslint/use-at-your-own-risk";
import {
  existsSync,
  globSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname } from "node:path";
import { format, resolveConfig } from "prettier";

const generatedHeader =
  "// Generated by `pnpm support codegen rules`. Do not edit.\n";

interface RuleSource {
  name: string;
  prefix: string;
  plugin: Plugin;
}

async function readRuleSources(root: string): Promise<RuleSource[]> {
  const configuredPlugins = await flatConfigsToPlugins(
    createEslintConfig(await loadConfig(root)),
  );

  const pluginSources = map(entries(configuredPlugins), ([prefix, plugin]) => {
    return {
      name: `${toPascalCase(prefix)}Rules`,
      prefix,
      plugin,
    };
  });

  return [
    {
      name: "CoreRules",
      prefix: "",
      plugin: {
        rules: record(builtinRules),
      },
    },
    ...pluginSources,
  ];
}

function normalizePluginSchemas(plugin: Plugin): Plugin {
  const rules = mappedValues(plugin.rules ?? {}, (rule) => {
    return {
      ...rule,
      meta: {
        ...rule.meta,
        schema: normalizeRuleSchema(rule.meta?.schema),
      },
    };
  });

  return {
    rules,
  };
}

async function createSourceModule({
  name,
  prefix,
  plugin,
}: RuleSource): Promise<string> {
  const declarations = await pluginsToRulesDTS(
    {
      [prefix]: normalizePluginSchemas(plugin),
    },
    {
      exportTypeName: name,
      includeAugmentation: false,
      includeIgnoreComments: false,
    },
  );

  return generatedHeader + declarations;
}

function createRulesModule(sources: RuleSource[]): string {
  const imports = map(sources, ({ name }) => {
    return `import type { ${name} } from "#eslint/types/rules/${name}";`;
  });

  const names = map(sources, ({ name }) => name);

  return [
    generatedHeader,
    ...imports,
    'import type { Linter } from "eslint";',
    "",
    `export interface Rules extends Partial<Linter.RulesRecord>, ${names.join(", ")} {}`,
  ].join("\n");
}

async function formatModule(path: string, content: string): Promise<string> {
  const options = await resolveConfig(path);

  return format(content, {
    ...options,
    filepath: path,
  });
}

export async function syncRuleTypes({
  root,
  check = false,
}: {
  root: Directory | URL;
  check?: boolean;
}): Promise<File[]> {
  const rootPath = resolve(root);

  const sources = await readRuleSources(rootPath);

  const modules = new Map<File, string>([
    [rulesFile, createRulesModule(sources)],
  ]);

  for (const source of sources) {
    modules.set(
      `${ruleSourcesDirectory}/${source.name}.ts`,
      await createSourceModule(source),
    );
  }

  const staleFiles = globSync(`${ruleSourcesDirectory}/*.ts`, {
    cwd: rootPath,
  }).filter((file) => !modules.has(file));

  const outdated: File[] = [...staleFiles];

  for (const [file, content] of modules) {
    const path = resolve(rootPath, file);

    const formatted = await formatModule(path, content);

    if (existsSync(path) && readFileSync(path, "utf8") === formatted) {
      continue;
    }

    outdated.push(file);

    if (!check) {
      mkdirSync(dirname(path), {
        recursive: true,
      });

      writeFileSync(path, formatted);
    }
  }

  if (!check) {
    for (const file of staleFiles) {
      rmSync(resolve(rootPath, file));
    }
  }

  return outdated.sort();
}
