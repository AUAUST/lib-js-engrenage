const apisDirectory = "data/apis";

const sharedFile: File = `${apisDirectory}/shared/common.d.ts`;

const sharedReference = "shared/common.d.ts";

// @debt Timer handles are typed `number`, the DOM signature, while Node returns an object; `setTimeout` results are not isomorphic.
const groupRoots: Record<string, readonly string[]> = {
  abort: ["AbortController", "AbortSignal"],
  blob: ["Blob", "File"],
  compression: ["CompressionStream", "DecompressionStream"],
  console: ["console"],
  crypto: ["crypto"],
  encoding: ["TextEncoder", "TextDecoder", "atob", "btoa"],
  events: ["Event", "EventTarget", "CustomEvent"],
  exceptions: ["DOMException"],
  microtasks: ["queueMicrotask"],
  performance: ["performance"],
  streams: [
    "ReadableStream",
    "WritableStream",
    "TransformStream",
    "ByteLengthQueuingStrategy",
    "CountQueuingStrategy",
    "TextEncoderStream",
    "TextDecoderStream",
  ],
  timers: ["setTimeout", "setInterval", "clearTimeout", "clearInterval"],
  url: ["URL", "URLSearchParams"],
};

function declaredNames(statement: Statement): string[] {
  if (
    isInterfaceDeclaration(statement) ||
    isTypeAliasDeclaration(statement) ||
    (isFunctionDeclaration(statement) && statement.name !== undefined)
  ) {
    return statement.name === undefined ? [] : [statement.name.text];
  }

  if (isVariableStatement(statement)) {
    return statement.declarationList.declarations.flatMap(({ name }) => {
      return isIdentifier(name) ? [name.text] : [];
    });
  }

  return [];
}

function leftmost(name: Node): string | undefined {
  let current = name;

  while (isQualifiedName(current)) {
    current = current.left;
  }

  while (isPropertyAccessExpression(current)) {
    current = current.expression;
  }

  return isIdentifier(current) ? current.text : undefined;
}

function referencedNames(statement: Statement): string[] {
  const names: string[] = [];

  function visit(node: Node) {
    let reference: EntityName | Node | undefined;

    if (isTypeReferenceNode(node)) {
      reference = node.typeName;
    } else if (isExpressionWithTypeArguments(node)) {
      reference = node.expression;
    } else if (isTypeQueryNode(node)) {
      reference = node.exprName;
    }

    const name = reference === undefined ? undefined : leftmost(reference);

    if (name !== undefined) {
      names.push(name);
    }

    forEachChild(node, visit);
  }

  visit(statement);

  return names;
}

function indexStatements(source: SourceFile): Map<string, number[]> {
  const index = new Map<string, number[]>();

  source.statements.forEach((statement, position) => {
    for (const name of declaredNames(statement)) {
      index.set(name, [...(index.get(name) ?? []), position]);
    }
  });

  return index;
}

function collectClosure(
  source: SourceFile,
  index: Map<string, number[]>,
  roots: readonly string[],
): Set<number> {
  const picked = new Set<number>();

  const queue = [...roots];

  const visited = new Set<string>();

  for (const root of roots) {
    if (!index.has(root)) {
      throw new Error(`lib.dom.d.ts declares no "${root}"`);
    }
  }

  while (queue.length > 0) {
    const name = queue.pop();

    if (name === undefined || visited.has(name)) {
      continue;
    }

    visited.add(name);

    for (const position of index.get(name) ?? []) {
      picked.add(position);

      const statement = source.statements[position];

      if (statement !== undefined) {
        queue.push(...referencedNames(statement));
      }
    }
  }

  return picked;
}

function readNotice(text: string): string {
  const end = text.indexOf("*/");

  return text.slice(0, end + 2);
}

function createModule({
  notice,
  reference,
  source,
  positions,
}: {
  notice: string;
  reference: boolean;
  source: SourceFile;
  positions: readonly number[];
}): string {
  const header = [
    notice,
    `// Generated by \`pnpm support codegen apis\` from the lib.dom.d.ts of TypeScript ${version}. Do not edit.`,
  ];

  const body = map(sort([...positions]), (position) => {
    return source.statements[position]?.getFullText(source).trim() ?? "";
  });

  return [
    ...header,
    ...(reference ? [`/// <reference path="${sharedReference}" />`] : []),
    "",
    body.join("\n\n"),
    "",
  ].join("\n");
}

async function formatModule(path: string, content: string): Promise<string> {
  const options = await resolveConfig(path);

  return format(content, {
    ...options,
    filepath: path,
  });
}

export async function syncApiDeclarations(
  config: ResolvedConfig,
  groups: readonly string[] = [],
) {
  const unknown = groups.filter((group) => !(group in groupRoots));

  if (unknown.length > 0) {
    throw new Error(
      `Unknown API groups: ${unknown.join(", ")}. Available groups: ${keys(groupRoots).join(", ")}`,
    );
  }

  const libraryPath = createRequire(import.meta.url).resolve(
    "typescript/lib/lib.dom.d.ts",
  );

  const text = readFileSync(libraryPath, "utf-8");

  const source = createSourceFile(
    "lib.dom.d.ts",
    text,
    ScriptTarget.ESNext,
    true,
  );

  const index = indexStatements(source);

  const closures = new Map(
    map(entries(groupRoots), ([group, roots]) => {
      return [group, collectClosure(source, index, roots)] as const;
    }),
  );

  const counts = new Map<number, number>();

  for (const closure of closures.values()) {
    for (const position of closure) {
      counts.set(position, (counts.get(position) ?? 0) + 1);
    }
  }

  const shared = new Set(
    filterMap(
      [...counts],
      ([, count]) => count > 1,
      ([position]) => position,
    ),
  );

  const notice = readNotice(text);

  const modules = new Map<File, string>([
    [
      sharedFile,
      createModule({
        notice,
        reference: false,
        source,
        positions: [...shared],
      }),
    ],
  ]);

  for (const [group, closure] of closures) {
    const own = [...closure].filter((position) => !shared.has(position));

    modules.set(
      `${apisDirectory}/${group}.d.ts`,
      createModule({
        notice,
        reference: own.length < closure.size,
        source,
        positions: own,
      }),
    );
  }

  for (const [file, content] of modules) {
    const isRequested =
      file === sharedFile ||
      groups.length === 0 ||
      groups.some((group) => file === `${apisDirectory}/${group}.d.ts`);

    if (isRequested) {
      config.filesystem.write(
        file,
        await formatModule(resolve(config.root, file), content),
      );
    }
  }
}
