import { describe, expect, test } from "vitest";

import { loadConfig } from "@auaust/engrenage/config";
import { syncWorkflowFiles } from "@auaust/engrenage/github";

import { createTemporaryProject } from "#tests/helpers/createTemporaryProject";

function createLibrary(scripts: Record<string, string>, config = "{}") {
  return createTemporaryProject({
    "engrenage.config.ts": `export default { presets: ["library"], github: ${config} };\n`,
    "package.json": JSON.stringify({
      type: "module",
      scripts,
      devDependencies: {
        "@changesets/cli": "*",
      },
    }),
  });
}

describe("syncWorkflowFiles", () => {
  test("generates the workflows of a changesets library with its script names", async () => {
    const project = createLibrary(
      {
        "release:check": "pnpm test",
        "release:publish": "changeset publish",
      },
      '{ prepareScript: "release:check", publishScript: "release:publish" }',
    );

    const config = await loadConfig(project.root);

    expect(
      syncWorkflowFiles({
        config,
      }),
    ).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "created",
      },
      {
        file: ".github/workflows/publish.yml",
        status: "created",
      },
    ]);

    const publish = project.read(".github/workflows/publish.yml");

    expect(publish).toMatch(/^# Generated by `engrenage sync workflows`/);
    expect(publish).toContain("pnpm run release:check\n");
    expect(publish).toContain('publish-script: "pnpm run release:publish"');
    expect(publish).not.toContain("{{");

    project.write(".github/workflows/ci.yml", "name: Edited\n");

    expect(
      syncWorkflowFiles({
        config,
        check: true,
      }),
    ).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "outdated",
      },
    ]);
  });

  test("requires the scripts and skips projects that do not qualify", async () => {
    const missingScript = createLibrary({
      "ci:prepare": "pnpm test",
    });

    const config = await loadConfig(missingScript.root);

    expect(() => {
      syncWorkflowFiles({
        config,
      });
    }).toThrow('does not declare the "ci:publish" script');

    const disabled = createLibrary({}, "{ workflows: false }");

    expect(
      syncWorkflowFiles({
        config: await loadConfig(disabled.root),
      }),
    ).toEqual([]);
  });
});
