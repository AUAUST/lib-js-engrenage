import { describe, expect, test } from "vitest";

import { loadConfig } from "@auaust/engrenage/config";
import { syncWorkflowFiles } from "@auaust/engrenage/github";

import { createTemporaryProject } from "#tests/helpers/createTemporaryProject";

const libraryScripts = {
  "ci:check": "engrenage sync --check",
  "ci:test": "vitest run",
  "ci:build": "tsdown",
  "ci:publish": "changeset publish",
};

function createLibrary(
  scripts: Record<string, string>,
  config = "{}",
  workflows: Record<string, string> = {
    ".github/workflows/ci.yml": "",
  },
) {
  return createTemporaryProject({
    ...workflows,
    "engrenage.config.ts": `export default { presets: ["library"], github: ${config} };\n`,
    "package.json": JSON.stringify({
      type: "module",
      scripts,
      devDependencies: {
        "@changesets/cli": "*",
      },
    }),
  });
}

describe("syncWorkflowFiles", () => {
  test("regenerates the existing library workflows and reports edits", async () => {
    const project = createLibrary(libraryScripts, "{}", {
      ".github/workflows/ci.yml": "",
      ".github/workflows/publish.yml": "",
    });

    const config = await loadConfig(project.root);

    expect(
      syncWorkflowFiles({
        config,
      }),
    ).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "synced",
      },
      {
        file: ".github/workflows/publish.yml",
        status: "synced",
      },
    ]);

    const publish = project.read(".github/workflows/publish.yml");

    expect(publish).toMatch(
      /^# Generated by `engrenage sync workflows` from the library workflows/,
    );
    expect(publish).toContain("run: pnpm run ci:check\n");
    expect(publish).toContain("publish-script: pnpm run ci:publish\n");

    project.write(".github/workflows/ci.yml", "name: Edited\n");

    expect(
      syncWorkflowFiles({
        config,
        check: true,
      }),
    ).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "outdated",
      },
    ]);
  });

  test("requires the ci scripts and skips disabled or absent workflows", async () => {
    const { "ci:test": _, ...withoutTest } = libraryScripts;

    const missingScript = createLibrary(withoutTest);

    const config = await loadConfig(missingScript.root);

    expect(() => {
      syncWorkflowFiles({
        config,
      });
    }).toThrow('does not declare the "ci:test" script');

    const disabled = createLibrary(libraryScripts, "{ workflows: false }");

    expect(
      syncWorkflowFiles({
        config: await loadConfig(disabled.root),
      }),
    ).toEqual([]);

    const absent = createLibrary(withoutTest, "{}", {});

    expect(
      syncWorkflowFiles({
        config: await loadConfig(absent.root),
      }),
    ).toEqual([]);
  });
});
