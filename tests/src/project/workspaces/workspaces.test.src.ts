import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { afterEach, describe, expect, test, vi } from "vitest";

import { checkWorkspaces } from "#batiment/structure/index";
import { loadConfig } from "#project/config/operations/loadConfig";
import { runSync } from "#project/sync/index";
import { buildLibraryCode } from "#tests/utils/buildLibraryCode";
import { createProjectLinter } from "#tests/utils/createProjectLinter";
import { createTemporaryProject } from "#tests/utils/createTemporaryProject";
import { mockCwd } from "#tests/utils/mockCwd";
import { runCommand } from "#tests/utils/runCommand";

import sync from "#bin/engrenage/sync";

const placeholder = "{dir}";

const config = `export default {
  environments: { src: { execution: { globals: "node", syntax: 24 } } },
  workspaces: { globs: {
    "extensions/action-*": { name: "@scope/app-${placeholder}" },
    "extensions/functions-*": { name: "@scope/fn-${placeholder}" },
  } },
};
`;

const files = {
  "engrenage.config.ts": config,
  "package.json": JSON.stringify({
    name: "app",
    type: "module",
    version: "1.2.3",
    license: "MIT",
  }),
  "tsconfig.json": "{}",
  "src/index.ts": "",
  "extensions/action-a/.workspace.json": "{}",
  "extensions/action-a/src/index.tsx": "",
  "extensions/action-a/package.json": JSON.stringify({
    shopify: { handle: "a" },
    dependencies: { "@scope/app-action-b": "workspace:*" },
  }),
  "extensions/action-b/.workspace.json": "{}",
  "extensions/action-b/src/index.ts": "",
  "extensions/functions-c/.workspace.json": "{}",
  "extensions/functions-c/src/index.ts": "",
};

function createProject() {
  const project = createTemporaryProject(files);

  mockCwd(project.root);

  return project;
}

afterEach(() => {
  vi.restoreAllMocks();
});

describe("workspaces", () => {
  test("syncs the workspace files of two globs, and a check reports drift", async () => {
    const project = createProject();

    await runCommand("sync", sync, "workspaces", "pnpm");

    expect(project.read("pnpm-workspace.yaml")).toContain(
      "packages:\n  - extensions/action-*\n  - extensions/functions-*\n",
    );

    expect(
      JSON.parse(project.read("extensions/action-a/package.json")),
    ).toEqual({
      name: "@scope/app-action-a",
      private: true,
      version: "1.2.3",
      license: "MIT",
      devEngines: {
        runtime: {
          name: "node",
          version: "24",
          onFail: "error",
        },
      },
      imports: {
        "#package.json": "./package.json",
      },
      shopify: {
        handle: "a",
      },
      dependencies: {
        "@scope/app-action-b": "workspace:*",
      },
    });

    expect(
      JSON.parse(project.read("extensions/functions-c/package.json")).name,
    ).toBe("@scope/fn-functions-c");

    expect(
      JSON.parse(project.read("extensions/action-b/package.json")).exports,
    ).toEqual({});

    expect(
      existsSync(project.resolve("extensions/action-b/tsconfig.json")),
    ).toBe(false);

    await runCommand("sync", sync, "workspaces", "pnpm", "--check");

    expect(process.exitCode).toBeUndefined();
  });

  test("writes the access of a published workspace at the root's visibility", async () => {
    const project = createProject();

    project.write(
      "engrenage.config.ts",
      config.replace("{\n", '{\n  visibility: "private",\n'),
    );

    project.write(
      "extensions/action-a/.workspace.json",
      JSON.stringify({
        traits: { enable: ["published"] },
      }),
    );

    await runCommand("sync", sync, "workspaces");

    expect(
      JSON.parse(project.read("extensions/action-a/package.json"))
        .publishConfig,
    ).toEqual({ access: "restricted" });

    expect(
      JSON.parse(project.read("extensions/action-b/package.json")),
    ).toMatchObject({ private: true });
  });

  test("removes a stale barrel its workspace's structure no longer plans", async () => {
    const project = createTemporaryProject({
      ...files,
      "extensions/action-b/src/.namespace.json": "{}",
      "extensions/action-b/src/greet/index.ts": "// Generated by `engrenage sync barrels` from the project structure. Do not edit.\n\nexport {};\n",
    });

    mockCwd(project.root);

    await runCommand("sync", sync, "barrels");

    expect(
      existsSync(project.resolve("extensions/action-b/src/greet/index.ts")),
    ).toBe(false);
  });

  test("writes the name a .workspace.json sets", async () => {
    const project = createProject();

    project.write(
      "extensions/action-b/.workspace.json",
      JSON.stringify({ name: "@scope/renamed" }),
    );

    await runCommand("sync", sync, "workspaces");

    expect(
      JSON.parse(project.read("extensions/action-b/package.json")).name,
    ).toBe("@scope/renamed");
  });

  test("writes each scope's own Node runtime", async () => {
    const project = createProject();

    project.write(
      "engrenage.config.ts",
      config.replace("{\n", "{\n  runtime: { node: 22 },\n"),
    );

    project.write(
      "extensions/action-b/.workspace.json",
      JSON.stringify({
        runtime: { node: 24 },
      }),
    );

    await runCommand("sync", sync, "package", "workspaces");

    function readRuntime(file: string) {
      return JSON.parse(project.read(file)).devEngines.runtime.version;
    }

    expect(readRuntime("extensions/action-b/package.json")).toBe("24");
    expect(readRuntime("extensions/action-a/package.json")).toBe("22");
    expect(readRuntime("package.json")).toBe("22");
  });

  test("reports a workspace file that drifted from the declaration", async () => {
    createProject().write(
      "extensions/action-b/package.json",
      JSON.stringify({ name: "wrong", private: true }),
    );

    const {
      messages,
    } = await runCommand("sync", sync, "workspaces", "--check");

    expect(process.exitCode).toBe(1);

    expect(messages.map(({ text }) => text)).toContain(
      "outdated: extensions/action-b/package.json",
    );

    process.exitCode = undefined;
  });

  test("detects the entry of a workspace holding only JavaScript", async () => {
    const project = createTemporaryProject({
      ...files,
      "extensions/action-d/.workspace.json": "{}",
      "extensions/action-d/src/index.js": "",
    });

    const groups = await (await loadConfig(project.root)).resolve("workspaces");

    expect(
      groups
        .flatMap(({ workspaces }) => workspaces)
        .find(({ dir }) => dir === "extensions/action-d")?.entry,
    ).toBe("extensions/action-d/src/index.js");
  });

  test("accepts a literal name for a glob without wildcard", async () => {
    const project = createTemporaryProject({
      ...files,
      "engrenage.config.ts": `export default { environments: { src: { execution: { globals: "node", syntax: 24 } } }, workspaces: { globs: { "theme": { name: "@scope/theme" } } } };\n`,
      "theme/.workspace.json": "{}",
      "theme/src/index.ts": "",
    });

    const groups = await (await loadConfig(project.root)).resolve("workspaces");

    expect(
      groups
        .flatMap(({ workspaces }) => {
          return workspaces;
        })
        .map(({ name }) => {
          return name;
        }),
    ).toEqual(["@scope/theme"]);
  });

  test("rejects a literal name for a wildcard glob", async () => {
    const project = createTemporaryProject({
      ...files,
      "engrenage.config.ts": `export default { environments: { src: { execution: { globals: "node", syntax: 24 } } }, workspaces: { globs: { "extensions/action-*": { name: "@scope/app" } } } };\n`,
    });

    await expect(
      (await loadConfig(project.root)).resolve("workspaces"),
    ).rejects.toThrow(
      `workspaces.globs.extensions/action-*.name must contain ${placeholder}`,
    );
  });

  test("checks workspace imports by package name against declared dependencies", async () => {
    const project = createProject();

    const config = await loadConfig(project.root);

    const grants = await config.resolve("importGrants");

    const entities = await config.resolve("entities");

    function check(file: string, targetFile: string) {
      const importer = entities.entityOf(project.resolve(file));
      const target = entities.entityOf(project.resolve(targetFile));

      expect(importer).toBeDefined();
      expect(target).toBeDefined();

      return checkWorkspaces(
        {
          file,
          importer,
          specifier: targetFile,
          resolved: target?.scope === undefined
            ? undefined
            : {
                kind: "scope",
                scope: target.scope,
                subpath: ".",
                exported: true,
              },
          targetFile,
          target,
          kind: "runtime",
        },
        grants,
      );
    }

    const actionA = "extensions/action-a/src/index.tsx";
    const actionB = "extensions/action-b/src/index.ts";
    const functionsC = "extensions/functions-c/src/index.ts";

    expect(entities.entityOf(project.resolve(actionA))).toMatchObject({
      scope: "extensions/action-a",
      namespace: undefined,
    });

    expect(check(actionA, actionB)).toBeUndefined();
    expect(check(actionA, actionA)).toBeUndefined();

    for (const [file, target] of [
      [actionA, functionsC],
      [actionB, actionA],
      [actionB, functionsC],
      ["src/index.ts", actionA],
      ["src/index.ts", actionB],
      ["src/index.ts", functionsC],
    ] as const) {
      expect(check(file, target)?.cause).toBe("scope");
    }
  });

  test("refuses with the scope message an import of a workspace from the root src", async () => {
    const { lint } = await createProjectLinter(config, {
      ...files,
      "src/index.ts": 'import "../extensions/action-a/src/index.tsx";\n',
    });

    const messages = await lint("src/index.ts", "auaust/import-workspaces");

    expect(messages.map(({ message }) => message)).toEqual([
      "`.` imports `extensions/action-a`, not a declared dependency of `.`.",
    ]);
  });

  describe("from a workspace into another scope", () => {
    const declaring = {
      ...files,
      "package.json": JSON.stringify({
        name: "app",
        type: "module",
        exports: {
          "./utils/json": "./src/utils/json.ts",
          "./utils/hidden": null,
          "./ui/*": "./src/ui/*.ts",
        },
      }),
      "src/utils/json.ts": "export {};\n",
      "extensions/action-a/package.json": JSON.stringify({
        name: "@scope/app-action-a",
        dependencies: {
          "app": "workspace:*",
          "@scope/app-action-b": "workspace:*",
        },
      }),
      "extensions/action-b/package.json": JSON.stringify({
        name: "@scope/app-action-b",
        exports: { ".": "./src/index.ts" },
      }),
      "extensions/functions-c/package.json": JSON.stringify({
        name: "@scope/fn-functions-c",
      }),
    };

    async function lintImports(...specifiers: string[]) {
      const { lint } = await createProjectLinter(config, {
        ...declaring,
        "extensions/action-a/src/imports.ts": specifiers
          .map((specifier) => `import "${specifier}";\n`)
          .join(""),
      });

      const messages = await lint(
        "extensions/action-a/src/imports.ts",
        (ruleId) => {
          return (
            ruleId === "auaust/import-workspaces" ||
            ruleId === "auaust/import-specifiers"
          );
        },
      );

      return messages.map(({ message }) => message);
    }

    test("refuses a relative path into the root, even a declared one, without suggesting a root alias", async () => {
      expect(await lintImports("../../../src/utils/json")).toEqual([
        "`extensions/action-a` reaches `.` through `../../../src/utils/json`; import it by package name, declared as a dependency.",
      ]);
    });

    test("refuses a package name without a declared dependency", async () => {
      expect(await lintImports("@scope/fn-functions-c")).toEqual([
        "`extensions/action-a` imports `extensions/functions-c`, not a declared dependency of `extensions/action-a`.",
      ]);
    });

    test("refuses a declared package name onto a subpath the target does not export", async () => {
      expect(
        await lintImports(
          "app/utils/other",
          "app/utils/hidden",
          "@scope/app-action-b/src/index",
        ),
      ).toEqual([
        "`app/utils/other` names a subpath `.` does not export.",
        "`app/utils/hidden` names a subpath `.` does not export.",
        "`@scope/app-action-b/src/index` names a subpath `extensions/action-b` does not export.",
      ]);
    });

    test("accepts a declared package name onto an exported subpath, patterns included", async () => {
      expect(
        await lintImports(
          "app/utils/json",
          "app/ui/button",
          "@scope/app-action-b",
        ),
      ).toEqual([]);
    });
  });
});

describe("workspace modules", () => {
  test("import their own aliased modules, type-check and build through Vite", async () => {
    const project = createTemporaryProject({
      "engrenage.config.ts": `export default {
        environments: { src: { execution: { globals: "node", syntax: 24 }, bundled: true } },
        typescript: { tsconfig: { extends: false, compilerOptions: { module: "ESNext", moduleResolution: "Bundler", target: "ESNext", strict: true, noEmit: true, skipLibCheck: true, lib: ["ESNext"], types: [] } } },
        workspaces: { globs: { "extensions/action-*": { name: "@scope/app-${placeholder}", environments: { src: { dirs: [] }, actions: { preset: "src", dirs: ["src"], execution: { globals: "browser", syntax: "2026-10" }, bundled: true } } } } },
      };\n`,
      "package.json": '{ "name": "app", "type": "module" }',
      "tsconfig.json": "{}",
      "src/index.ts": "",
      "extensions/action-a/.workspace.json": "{}",
      "extensions/action-a/src/helper.ts": "export const helper: string = 'helped';\n",
      "extensions/action-a/src/index.ts": "import { helper } from '#helper';\n\nexport const message: string = `hello ${helper}`;\n",
    });

    const resolved = await loadConfig(project.root);

    await runSync(resolved, {
      names: ["tsconfig", "aliases", "workspaces"],
    });

    await resolved.context.filesystem.flush();

    execFileSync(
      process.execPath,
      [
        fileURLToPath(import.meta.resolve("typescript/bin/tsc")),
        "-p",
        "extensions/action-a/tsconfig.actions.json",
      ],
      { cwd: project.root, stdio: "pipe" },
    );

    const code = await buildLibraryCode(
      project.root,
      "extensions/action-a/src/index.ts",
    );

    expect(code).toContain("hello");
    expect(code).toContain("helped");
  });
});

describe("workspace tsconfigs", () => {
  async function syncTheme(environments: Record<string, unknown>) {
    const project = createTemporaryProject({
      "engrenage.config.ts": `export default {
        environments: { src: { execution: { globals: "node", syntax: 24 } } },
        workspaces: { globs: { theme: { name: "@scope/theme" } } },
      };\n`,
      "package.json": '{ "name": "app", "type": "module" }',
      "tsconfig.json": "{}",
      "src/index.ts": "",
      "theme/.workspace.json": JSON.stringify({
        environments: {
          src: { dirs: [] },
          ...environments,
        },
      }),
      "theme/src/index.ts": "",
      "theme/src/worker/index.ts": "",
    });

    const resolved = await loadConfig(project.root);

    await runSync(resolved, { names: ["tsconfig", "workspaces"] });

    await resolved.context.filesystem.flush();

    return project;
  }

  test("gives a workspace instance its own tsconfig, referenced by the base one", async () => {
    const project = await syncTheme({
      web: {
        preset: "src",
        dirs: ["src"],
        execution: { globals: "browser", syntax: "2026-10" },
      },
      worker: {
        preset: "bin",
        dirs: ["src/worker"],
      },
    });

    expect(JSON.parse(project.read("theme/tsconfig.web.json"))).toMatchObject({
      extends: "../tsconfig.json",
      include: ["src/**/*.ts"],
      exclude: ["src/worker/**"],
    });

    expect(JSON.parse(project.read("tsconfig.json")).references).toEqual(
      expect.arrayContaining([
        { path: "./theme/tsconfig.web.json" },
        { path: "./theme/tsconfig.worker.json" },
      ]),
    );

    expect(existsSync(project.resolve("theme/tsconfig.json"))).toBe(false);
  });

  test("writes a registration's tsconfig path inside the workspace", async () => {
    const project = await syncTheme({
      web: {
        preset: "src",
        dirs: ["src"],
        execution: {
          globals: "browser",
          syntax: "2026-10",
        },
        tsconfig: {
          path: "tsconfig.json",
          compilerOptions: { jsx: "preserve" },
        },
      },
    });

    expect(
      JSON.parse(project.read("theme/tsconfig.json")).compilerOptions.jsx,
    ).toBe("preserve");
  });

  test("rejects two tsconfigs resolving to one file", async () => {
    await expect(
      syncTheme({
        web: {
          preset: "src",
          dirs: ["src"],
          execution: { globals: "browser", syntax: "2026-10" },
          tsconfig: { path: "tsconfig.app.json" },
        },
        worker: {
          preset: "bin",
          dirs: ["src/worker"],
          tsconfig: { path: "tsconfig.app.json" },
        },
      }),
    ).rejects.toThrow(
      "the web tsconfig in theme and the worker tsconfig in theme both resolve to theme/tsconfig.app.json",
    );
  });
});
