import { parseTOML } from "confbox/toml";
import { describe, expect, test, vi } from "vitest";

import { loadConfig } from "#project/config/operations/loadConfig";
import { createTemporaryProject } from "#tests/utils/createTemporaryProject";
import { claudeStopHook } from "#tools/agents/claude/constants";
import { getSkillTemplates } from "#tools/agents/operations/getSkillTemplates";
import { createHookCommand } from "#tools/agents/utils/createHookCommand";

const skill = vi.hoisted(() => {
  return {
    name: "",
    agent: {},
  };
});

vi.mock(import("#tools/agents/operations/getInstructionTemplates"), () => {
  return {
    getInstructionTemplates: () => {
      return Promise.resolve([
        {
          title: skill.name,
          description: `${skill.name} skill`,
          category: "workflow",
          default: false,
          order: 0,
          name: skill.name,
          source: `/skills/${skill.name}.md`,
          reference: `@auaust/engrenage/agents/skills/${skill.name}.md`,
          body: `# ${skill.name}`,
          paths: undefined,
          agent: skill.agent,
        },
      ]);
    },
  };
});

function mockSkill(name: string, agent: object) {
  skill.name = name;
  skill.agent = agent;
}

async function renderSkills(preferred = ["claude"]) {
  const project = createTemporaryProject({
    "package.json": '{"type":"module"}',
    "engrenage.config.ts": `export default { agents: { preferred: ${JSON.stringify(preferred)} } };`,
  });

  const config = await loadConfig(project.root);

  const agents = await config.resolve("agents");

  return getSkillTemplates({
    agents,
    fillers: {},
  });
}

async function renderAgentFrontmatter() {
  const [template] = await renderSkills();

  return template?.files.find(({ file }) => {
    return file.startsWith(".claude/agents/");
  })?.frontmatter?.values;
}

describe("getSkillTemplates", () => {
  test("retains canonical metadata and renders one profile per distinct complexity effort", async () => {
    mockSkill("issue-implementation", {
      name: "worker",
      description: "Canonical worker",
      model: "opus",
      effort: "low",
      efforts: {
        trivial: "low",
        involved: "medium",
        complex: "medium",
      },
      gate: true,
    });

    const [template] = await renderSkills(["codex"]);

    expect(template?.agent).toMatchObject({
      model: "opus",
      gate: true,
    });

    expect(
      template?.profiles.map(({ name, role, effort, gate }) => {
        return {
          name,
          role,
          effort,
          gate,
        };
      }),
    ).toEqual([
      {
        name: "worker",
        role: "worker",
        effort: "low",
        gate: true,
      },
      {
        name: "worker_medium",
        role: "worker",
        effort: "medium",
        gate: true,
      },
    ]);

    for (const profile of template?.profiles ?? []) {
      const parsed = parseTOML<Record<string, unknown>>(profile.content);

      expect(parsed).not.toHaveProperty("model");

      expect(parsed).toMatchObject({
        name: profile.name,
        description: "Canonical worker",
        model_reasoning_effort: profile.effort,
      });

      expect(parsed.developer_instructions).toMatch(
        /AGENTS\.md[\s\S]*All files[\s\S]*# issue-implementation/,
      );

      expect(profile.content).toMatch(
        /^# Generated by engrenage from @auaust\/engrenage\/agents\/skills\/issue-implementation\.md/,
      );
    }
  });

  test("rejects an invalid agent effort, naming the skill source", async () => {
    mockSkill("broken", {
      name: "breaker",
      description: "Breaker",
      effort: "extreme",
    });

    await expect(renderSkills()).rejects.toThrow(
      /\/skills\/broken\.md skill metadata[\s\S]*received "extreme"[\s\S]*agent\.effort/,
    );
  });

  test("renders the stop hook for a gated agent, without its gate and efforts keys", async () => {
    mockSkill("gated", {
      name: "worker",
      description: "Worker",
      efforts: { complex: "high" },
      gate: true,
    });

    expect(await renderAgentFrontmatter()).toEqual({
      name: "worker",
      description: "Worker",
      hooks: {
        Stop: [
          {
            hooks: [
              {
                type: "command",
                command: createHookCommand(claudeStopHook.command),
              },
            ],
          },
        ],
      },
    });
  });

  test("renders no hooks for an ungated agent", async () => {
    mockSkill("ungated", { name: "helper", description: "Helper" });

    expect(await renderAgentFrontmatter()).toEqual({
      name: "helper",
      description: "Helper",
    });
  });

  test("renders the tool allowlist into the Claude agent only", async () => {
    mockSkill("allowlisted", {
      name: "helper",
      description: "Helper",
      tools: ["Bash", "Read"],
    });

    expect(await renderAgentFrontmatter()).toEqual({
      name: "helper",
      description: "Helper",
      tools: ["Bash", "Read"],
    });

    const [template] = await renderSkills(["codex"]);

    for (const profile of template?.profiles ?? []) {
      expect(
        parseTOML<Record<string, unknown>>(profile.content),
      ).not.toHaveProperty("tools");
    }
  });

  test("rejects a non-string tool, naming the skill source", async () => {
    mockSkill("broken", {
      name: "breaker",
      description: "Breaker",
      tools: ["Bash", 1],
    });

    await expect(renderSkills()).rejects.toThrow(
      /\/skills\/broken\.md skill metadata[\s\S]*agent\.tools/,
    );
  });
});
