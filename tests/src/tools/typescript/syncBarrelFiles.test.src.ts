import { existsSync } from "node:fs";

import { ESLint } from "eslint";
import { assert, describe, expect, test } from "vitest";

import {
  createRolePreset,
  enums,
  schemas,
  types,
  utils,
  type Role,
} from "#project/roles/index";
import { collectChanges, runSync } from "#project/sync/index";
import { createBarrelProject } from "#tests/utils/createBarrelProject";
import { createEslintConfig } from "#tools/eslint/index";
import { createBarrelRenderer } from "#tools/typescript/operations/createBarrelRenderer";
import { planBarrels } from "#tools/typescript/operations/planBarrels";
import { loadValidatedConfig } from "#workflows/config/index";
import type { BarrelExport } from "#tools/typescript/index";

const header = "// Generated by `engrenage sync barrels` from the project structure. Do not edit.\n\n";

function createKit({
  files,
  guard = { reexport: "flat" },
  object = {},
  roles = [],
  namespaces = {},
  extensions = [],
}: {
  files: Record<string, string>;
  guard?: Record<string, unknown>;
  object?: Record<string, unknown>;
  roles?: readonly Role[];
  namespaces?: Record<string, Record<string, unknown>>;
  extensions?: readonly unknown[];
}) {
  return createBarrelProject({
    files,
    roles: [utils({ collected: true, public: true }), ...roles],
    domains: {
      "*": { public: true },
      guard,
      object,
    },
    namespaces,
    extensions,
  });
}

describe("barrels sync target", () => {
  test("writes an entry-only domain's entry and a root entry re-exporting it, which sync --check then accepts", async () => {
    const { project, config, sync } = createKit({
      files: {
        "src/modules/object/utils/keys.ts": "export function keys() {}\n",
        "src/modules/object/utils/hasOwn.ts": "export function hasOwn() {}\n",
        "src/modules/guard/utils/isString.ts": "export function isString() {}\n",
      },
    });

    await sync();

    expect(project.read("src/modules/object/entry.ts")).toBe(
      `${header}export { hasOwn } from "#modules/object/utils/hasOwn";
export { keys } from "#modules/object/utils/keys";
export type * from "#modules/object/utils/hasOwn";
export type * from "#modules/object/utils/keys";
`,
    );

    expect(project.read("src/entry.ts")).toBe(
      `${header}export * from "#modules/guard/entry";
export * as object from "#modules/object/entry";
`,
    );

    const copy = config.context.copy();

    expect(await runSync(copy)).toEqual([]);
    expect(await collectChanges(copy, { check: true })).toEqual([]);
  });

  test("orders a barrel mixing export groups as the export order lint wants", async () => {
    const { project, config, sync } = createKit({
      files: {
        "src/modules/object/utils/keys10.ts": "export function keys10() {}\n",
        "src/modules/object/utils/keys2.ts": "export function keys2() {}\n",
        "src/modules/object/schemas/shape.ts": "export const shape = {};\n",
        "src/modules/object/enums/Kind.ts": "export type Kind = string;\n",
        "src/modules/object/types/Entry.ts": "export interface Entry {}\n",
      },
      roles: [
        schemas({
          exports: "named",
          collected: true,
          public: true,
        }),
        enums({
          exports: { values: "none", types: "named-match" },
          collected: true,
          public: true,
        }),
        types({ collected: true, public: true }),
      ],
    });

    await sync();

    const barrel = project.read("src/modules/object/entry.ts");

    expect(barrel).toBe(
      `${header}export { keys2 } from "#modules/object/utils/keys2";
export { keys10 } from "#modules/object/utils/keys10";
export type { Kind } from "#modules/object/enums/Kind";
export * from "#modules/object/schemas/shape";
export type * from "#modules/object/types/Entry";
export type * from "#modules/object/utils/keys2";
export type * from "#modules/object/utils/keys10";
`,
    );

    const eslint = new ESLint({
      cwd: project.root,
      overrideConfigFile: true,
      overrideConfig: await createEslintConfig(config, { typeAware: false }),
    });

    const [result] = await eslint.lintText(barrel, {
      filePath: project.resolve("src/modules/object/entry.ts"),
    });

    expect(
      (result?.messages ?? []).filter(({ ruleId }) => {
        return ruleId === "auaust/sort-exports";
      }),
    ).toEqual([]);
  });

  test("exports a domain listing both re-export forms as a namespace and spreads its names", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/guard/utils/isString.ts": "export function isString() {}\n",
      },
      guard: {
        reexport: ["namespace", "flat"],
      },
    });

    await sync();

    expect(project.read("src/entry.ts")).toBe(
      `${header}export * from "#modules/guard/entry";
export * as guard from "#modules/guard/entry";
`,
    );
  });

  test("spreads the barrel of a global index role declaring `reexport` from the root entry, and only then", async () => {
    const files = {
      "src/modules/guard/utils/isString.ts": "export function isString() {}\n",
      "src/types/Shape.ts": "export interface Shape {}\n",
    };

    const reexported = createKit({
      files,
      roles: [types({ index: true, reexport: "flat" })],
    });

    await reexported.sync();

    expect(reexported.project.read("src/entry.ts")).toBe(
      `${header}export * from "#modules/guard/entry";
export type * from "#types/index";
`,
    );

    const unexported = createKit({
      files,
      roles: [types({ index: true })],
    });

    await unexported.sync();

    expect(unexported.project.read("src/types/index.ts")).toBe(
      `${header}export type * from "#types/Shape";\n`,
    );

    expect(unexported.project.read("src/entry.ts")).not.toContain(
      "#types/index",
    );
  });

  test("fails on two flat domains exporting one name, naming both files", async () => {
    const { config } = createKit({
      files: {
        "src/modules/object/utils/isString.ts": "export function isString() {}\n",
        "src/modules/guard/utils/isString.ts": "export function isString() {}\n",
      },
      object: {
        reexport: "flat",
      },
    });

    await expect(runSync(config)).rejects.toThrow(
      '"isString" is exported by both src/modules/guard/utils/isString.ts and src/modules/object/utils/isString.ts in src/entry.ts',
    );
  });

  test("lists a role collected from every domain in an entry declaring `collects`, besides its own modules", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/a/utils/isA.ts": "export function isA() {}\n",
        "src/modules/b/utils/isB.ts": "export function isB() {}\n",
        "src/modules/guard/utils/isNull.ts": "export function isNull() {}\n",
      },
      guard: {
        collects: ["utils"],
      },
    });

    await sync();

    expect(project.read("src/modules/guard/entry.ts")).toBe(
      `${header}export { isA } from "#modules/a/utils/isA";
export { isB } from "#modules/b/utils/isB";
export { isNull } from "#modules/guard/utils/isNull";
export type * from "#modules/a/utils/isA";
export type * from "#modules/b/utils/isB";
export type * from "#modules/guard/utils/isNull";
`,
    );

    expect(project.read("src/modules/a/entry.ts")).toBe(
      `${header}export { isA } from "#modules/a/utils/isA";
export type * from "#modules/a/utils/isA";
`,
    );
  });

  test("removes a generated barrel in a role without `index` and leaves it out of the domain's entry in one sync", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/a/utils/isA.ts": "export function isA() {}\n",
        "src/modules/a/utils/index.ts": `${header}export { isA } from "#modules/a/utils/isA";\n`,
      },
    });

    await sync();

    expect(existsSync(project.resolve("src/modules/a/utils/index.ts"))).toBe(
      false,
    );

    expect(project.read("src/modules/a/entry.ts")).toBe(
      `${header}export { isA } from "#modules/a/utils/isA";
export type * from "#modules/a/utils/isA";
`,
    );
  });

  test("keeps a hand-written `index.ts` in a role without `index` as a module of the domain's entry", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/a/utils/isA.ts": "export function isA() {}\n",
        "src/modules/a/utils/index.ts": "export function index() {}\n",
      },
    });

    await sync();

    expect(project.read("src/modules/a/utils/index.ts")).toBe(
      "export function index() {}\n",
    );

    expect(project.read("src/modules/a/entry.ts")).toContain(
      'from "#modules/a/utils/index";',
    );
  });

  test("lists the modules of a collected role with a root-only subpath in its domain's entry", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/d/models/shape.ts": "export function shape() {}\n",
      },
      roles: [
        createRolePreset({
          name: "models",
          index: true,
          public: true,
          collected: true,
          subpath: "root",
        })(),
      ],
    });

    await sync();

    expect(project.read("src/modules/d/entry.ts")).toContain(
      'from "#modules/d/models/shape";',
    );
  });

  test("generates a root-only index role's barrel at the environment root only, listing a domain's modules in its entry", async () => {
    const { project, sync } = createKit({
      files: {
        "src/models/point.ts": "export function point() {}\n",
        "src/modules/d/models/shape.ts": "export function shape() {}\n",
      },
      roles: [
        createRolePreset({
          name: "models",
          index: "root",
          public: true,
          collected: true,
          subpath: "root",
        })(),
      ],
    });

    await sync();

    expect(project.read("src/models/index.ts")).toContain(
      'from "#models/point";',
    );

    expect(existsSync(project.resolve("src/modules/d/models/index.ts"))).toBe(
      false,
    );

    expect(project.read("src/modules/d/entry.ts")).toContain(
      'from "#modules/d/models/shape";',
    );
  });

  test("lists in an entry declaring `collects` a collected role enabled only by another namespace", async () => {
    const { project, sync } = createKit({
      files: {
        "src/x/a/guards/isA.ts": "export function isA() {}\n",
        "src/x/b/guards/isB.ts": "export function isB() {}\n",
        "src/modules/guard/utils/isNull.ts": "export function isNull() {}\n",
      },
      guard: {
        collects: ["guards"],
      },
      roles: [
        createRolePreset({
          name: "guards",
          public: true,
          collected: true,
          scoped: true,
        })(),
      ],
      namespaces: {
        x: {
          children: "domains",
          roles: {
            enable: ["guards"],
          },
          domains: {
            "*": { public: true },
          },
        },
      },
    });

    await sync();

    expect(project.read("src/modules/guard/entry.ts")).toBe(
      `${header}export { isNull } from "#modules/guard/utils/isNull";
export * from "#x/a/guards/isA";
export * from "#x/b/guards/isB";
export type * from "#modules/guard/utils/isNull";
`,
    );
  });

  test("fails resolution when `collects` names a private role, naming the role", async () => {
    const { config } = createKit({
      files: {
        "src/modules/guard/types/Guard.ts": "export type Guard = unknown;\n",
      },
      guard: {
        collects: ["types"],
      },
      roles: [types({ public: false })],
    });

    await expect(runSync(config)).rejects.toThrow(
      "src/modules/guard collects the role types, which is not a public collected role of its environment",
    );
  });

  test("adds the aliases a contribution returns to the module's entry", async () => {
    const { project, sync } = createKit({
      files: {
        "src/modules/object/utils/toString.ts": "export function toString() {}\n",
      },
      extensions: [
        {
          name: "shorthands",
          contributes: {
            "barrels.exports": [
              {
                name: "shorthands",
                load() {
                  return Promise.resolve(
                    (_node: unknown, exports: readonly BarrelExport[]) => {
                      return [
                        ...exports,
                        ...exports
                          .filter(({ binding }) => binding === "toString")
                          .map((exported) => {
                            return { ...exported, name: "s" };
                          }),
                      ];
                    },
                  );
                },
              },
            ],
          },
        },
      ],
    });

    await sync();

    expect(project.read("src/modules/object/entry.ts")).toContain(
      'export { toString as s } from "#modules/object/utils/toString";',
    );
  });

  test("lists engrenage's built-in extensions in its collecting entry under their domain names", async () => {
    const config = await loadValidatedConfig();

    const [
      plans,
      render,
    ] = await Promise.all([planBarrels(config), createBarrelRenderer(config)]);

    const plan = plans.find(({ file }) => {
      return file === "src/workflows/builtins/entry.ts";
    });

    assert(plan !== undefined);

    const { lines } = await render(plan, new Map());

    expect(lines).toHaveLength(35);

    expect(lines).toContain(
      'export { default as projectBuild } from "#project/build/extension";',
    );

    expect(lines).toContain(
      'export { default as toolsShopifyTheme } from "#tools/shopify/theme/extension";',
    );

    expect(lines.join("\n")).not.toContain("roles/operations/extension");
  });
});
