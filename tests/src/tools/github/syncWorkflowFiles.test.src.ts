import { describe, expect, test } from "vitest";

import { createTemporaryProject } from "#tests/utils/createTemporaryProject";
import { syncWorkflowFiles } from "#tools/github/setup/syncWorkflowFiles";
import { loadConfig } from "#workflows/registry/operations/loadConfig";
import { readConfig } from "#workflows/registry/operations/readConfig";

const libraryScripts = {
  "ci:check": "engrenage sync --check",
  "ci:test": "vitest run",
  "ci:build": "tsdown",
  "ci:publish": "changeset publish",
};

const ciWorkflow = {
  ".github/workflows/ci.yml": "",
};

function createLibrary(
  scripts: Record<string, string>,
  config = "{}",
  workflows?: Record<string, string>,
) {
  return createTemporaryProject({
    ...(workflows ?? ciWorkflow),
    "engrenage.config.ts": `export default { preset: "library", github: ${config} };\n`,
    "package.json": JSON.stringify({
      type: "module",
      scripts,
      devDependencies: {
        "@changesets/cli": "*",
      },
    }),
  });
}

describe("syncWorkflowFiles", () => {
  test("regenerates the existing library workflows and reports edits", async () => {
    const project = createLibrary(libraryScripts, "{}", {
      ".github/workflows/ci.yml": "",
      ".github/workflows/publish.yml": "",
    });

    const config = await loadConfig(project.root);

    await syncWorkflowFiles(config);

    expect((await config.get("filesystem")).flush()).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "synced",
      },
      {
        file: ".github/workflows/publish.yml",
        status: "synced",
      },
    ]);

    const publish = project.read(".github/workflows/publish.yml");

    expect(publish).toMatch(
      /^# Generated by `engrenage sync workflows` from the library workflows/,
    );

    expect(publish).toContain("run: pnpm run ci:check\n");
    expect(publish).toContain("publish-script: pnpm run ci:publish\n");

    project.write(".github/workflows/ci.yml", "name: Edited\n");

    const edited = await readConfig(project.root);

    await syncWorkflowFiles(edited);

    expect((await edited.get("filesystem")).changes()).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "synced",
      },
    ]);
  });

  test("requires the ci scripts and skips disabled or absent workflows", async () => {
    const { "ci:test": _, ...withoutTest } = libraryScripts;

    const missingScript = createLibrary(withoutTest);

    const config = await loadConfig(missingScript.root);

    await expect(async () => {
      await syncWorkflowFiles(config);
    }).rejects.toThrow('does not declare the "ci:test" script');

    const disabled = createLibrary(libraryScripts, "{ workflows: false }");

    const disabledConfig = await loadConfig(disabled.root);

    await syncWorkflowFiles(disabledConfig);

    expect((await disabledConfig.get("filesystem")).changes()).toEqual([]);

    const absent = createLibrary(withoutTest, "{}", {});

    const absentConfig = await loadConfig(absent.root);

    await syncWorkflowFiles(absentConfig);

    expect((await absentConfig.get("filesystem")).changes()).toEqual([]);
  });

  test("writes the workflows under the repository root with the project as working directory", async () => {
    const project = createTemporaryProject({
      ".git/HEAD": "",
      ".github/workflows/ci.yml": "",
      "packages/app/engrenage.config.ts":
        'export default { preset: "library" };\n',
      "packages/app/package.json": JSON.stringify({
        type: "module",
        scripts: libraryScripts,
        devDependencies: {
          "@changesets/cli": "*",
        },
      }),
    });

    const config = await loadConfig(project.resolve("packages/app"));

    await syncWorkflowFiles(config);

    expect((await config.get("git")).root).toBe(project.root);
    expect((await config.get("filesystem")).changes()).toEqual([]);

    expect((await config.get("git")).filesystem.flush()).toEqual([
      {
        file: ".github/workflows/ci.yml",
        status: "synced",
      },
    ]);

    expect(project.read(".github/workflows/ci.yml")).toContain(
      "working-directory: packages/app",
    );
  });
});
