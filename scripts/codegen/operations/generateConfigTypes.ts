import { getDescription, strictObject } from "valibot";

import { iterable } from "@auaust/toolkit";

import { roleGlobsSchema, roleRulesSchema } from "#batiment/roles/index";
import { buildToolNameSchema } from "#project/build/index";
import { tagDeclarationSchema } from "#project/docs/index";
import { formatterNameSchema } from "#project/format/index";
import { presetNameSchema } from "#project/presets/index";
import { collectConfigInputs } from "#scripts/codegen/operations/collectConfigInputs";
import { composeInputSchemas } from "#scripts/codegen/operations/composeInputSchemas";
import { renderConfigType } from "#scripts/codegen/operations/renderConfigType";
import { findConfigTypeImports } from "#scripts/codegen/utils/findConfigTypeImports";
import { isConfigSchema } from "#scripts/codegen/utils/isConfigSchema";
import { preferredSchema } from "#tools/metalbrain/index";
import type { LoadedConfig } from "#project/config/index";
import type { ConfigSchema } from "#scripts/codegen/types/ConfigSchema";
import type { TypeSource } from "#scripts/codegen/types/TypeSource";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";

const composedDomain: Directory = "workflows/config";

const composedName = "BuiltinConfigInput";

const composedFile: File = "src/workflows/config/types/ConfigInput.ts";

const generatedHeader = "// Generated by `pnpm engrenage run codegen config`. Do not edit.\n";

const externalTypes = new Map<string, TypeSource>([
  ["ListOption", { domain: "foundation/options", specifier: undefined }],
  ["ManagedListOption", { domain: "foundation/options", specifier: undefined }],
  ["GlobalsFactory", { domain: "project/environments", specifier: undefined }],
  ["ExtensionOption", { domain: "project/config", specifier: undefined }],
  ["RoleRules", { domain: "batiment/roles", specifier: undefined }],
  ["TagDeclaration", { domain: "project/docs", specifier: undefined }],
  ["Glob", { domain: undefined, specifier: "#types/Glob" }],
  ["Globs", { domain: undefined, specifier: "#types/Globs" }],
]);

const namedTypes = new Map<unknown, string>([
  [buildToolNameSchema, "keyof Engrenage.BuildTools"],
  [formatterNameSchema, "keyof Engrenage.Formatters"],
  [presetNameSchema, "keyof Engrenage.Presets"],
  [preferredSchema, "(keyof Engrenage.AgentRuntimes)[]"],
  [roleGlobsSchema, "Glob | Globs"],
  [roleRulesSchema, "RoleRules"],
  [tagDeclarationSchema, "TagDeclaration"],
]);

function descriptionOf(schema: ConfigSchema): string | undefined {
  return getDescription(
    "wrapped" in schema && isConfigSchema(schema.wrapped)
      ? schema.wrapped
      : schema,
  );
}

export async function generateConfigTypes(
  config: LoadedConfig,
  modules: ReadonlyMap<File, Readonly<Record<string, unknown>>>,
) {
  const sections = await composeInputSchemas(config);

  const root = strictObject(sections);
  const named = new Set(namedTypes.keys());
  const inputs = collectConfigInputs(modules, sections, root, named);

  const names = new Map(
    iterable.map([...inputs], ([core, { name }]) => [core, name] as const),
  );

  const sources = new Map(externalTypes);

  for (const { name, domain } of inputs.values()) {
    sources.set(name, { domain, specifier: undefined });
  }

  const files = [
    ...iterable.map([...inputs], ([core, { name, domain, declaration }]) => {
      return {
        name,
        domain,
        file: `src/${domain}/types/${name}.ts`,
        core,
        description: descriptionOf(declaration.schema),
        trailer: [],
      };
    }),
    {
      name: composedName,
      domain: composedDomain,
      file: composedFile,
      core: root,
      description: undefined,
      trailer: [
        "declare global {",
        "  namespace Engrenage {",
        `    interface ConfigInput extends ${composedName} {}`,
        "  }",
        "}",
        "",
        "export type ConfigInput = Engrenage.ConfigInput;",
        "",
      ],
    },
  ];

  for (const { name, domain, file, core, description, trailer } of files) {
    const declarations = await renderConfigType({
      core,
      name,
      names,
      types: namedTypes,
      description,
    });

    const filesystem = config.context.filesystem;

    await filesystem.write(
      file,
      [
        generatedHeader,
        ...findConfigTypeImports(declarations, name, domain, sources),
        "",
        declarations,
        ...trailer,
      ].join("\n"),
    );
  }
}
