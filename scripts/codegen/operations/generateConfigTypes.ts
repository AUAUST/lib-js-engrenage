const composedDomain: Directory = "workflows/config";

const composedName = "BuiltinConfigInput";

const composedFile: File = "src/workflows/config/types/ConfigInput.ts";

const namedReference = "#named/";

const generatedHeader = "// Generated by `pnpm support codegen config`. Do not edit.\n";

const externalTypes = new Map<string, TypeSource>([
  ["ListOption", { domain: "foundation/options", specifier: undefined }],
  ["ManagedListOption", { domain: "foundation/options", specifier: undefined }],
  ["GlobalsFactory", { domain: "project/environments", specifier: undefined }],
  ["Extension", { domain: "project/config", specifier: undefined }],
  [
    "EffectModuleResolver",
    { domain: "project/structure", specifier: undefined },
  ],
  ["RoleRules", { domain: "project/roles", specifier: undefined }],
  ["RoleFileResolver", { domain: "project/roles", specifier: undefined }],
  ["Glob", { domain: undefined, specifier: "#types/Glob" }],
  ["Globs", { domain: undefined, specifier: "#types/Globs" }],
]);

function findListItem(schema: ConfigSchema): ConfigSchema | undefined {
  if (!isUnionConfigSchema(schema) || schema.options.length !== 2) {
    return;
  }

  const [items, adjustment] = schema.options;

  if (!isListAdjustmentSchema(adjustment) || !isUnionConfigSchema(items)) {
    return;
  }

  return items.options[0];
}

function findManagedListItem(schema: ConfigSchema): ConfigSchema | undefined {
  if (!isUnionConfigSchema(schema) || schema.options.length !== 2) {
    return;
  }

  const [list, flag] = schema.options;

  return flag.type === "boolean" ? findListItem(list) : undefined;
}

function renderItem(schema: ConfigSchema): string {
  const { type, enum: values } = toJsonSchema(schema, {
    errorMode: "throw",
  }) as { type?: string; enum?: readonly string[] };

  if (type === "string" && values === undefined) {
    return "string";
  }

  if (values !== undefined) {
    return values.map((value) => JSON.stringify(value)).join(" | ");
  }

  throw new Error(
    `The list item of type ${schema.type} has no TypeScript form`,
  );
}

function optionsOf(schema: object): unknown {
  return "options" in schema ? schema.options : undefined;
}

const readonlyListTypes = new Map<unknown, string>([
  [optionsOf(globsSchema), "Glob | Globs"],
]);

const namedTypes = new Map<unknown, string>([
  [buildToolNameSchema, "keyof EngrenageBuildTools"],
  [formatterNameSchema, "keyof EngrenageFormatters"],
  [presetNameSchema, "keyof EngrenagePresets"],
  [inheritsSchema, "keyof EngrenageEnvironments"],
  [preferredSchema, "(keyof EngrenageAgentRuntimes)[]"],
]);

function resolveType(schema: ConfigSchema): string | undefined {
  const named = namedTypes.get(schema);

  if (named !== undefined) {
    return named;
  }

  if (schema === effectModuleResolverSchema) {
    return "EffectModuleResolver";
  }

  if (schema === roleFileResolverSchema) {
    return "RoleFileResolver";
  }

  if (schema === roleRulesSchema) {
    return "RoleRules";
  }

  if (schema === extensionSchema) {
    return "Extension";
  }

  // @debt every other custom schema is read as `GlobalsFactory`; each named custom schema should map to its own type
  if (schema.type === "custom") {
    return "GlobalsFactory";
  }

  const readonlyList = readonlyListTypes.get(optionsOf(schema));

  if (readonlyList !== undefined) {
    return readonlyList;
  }

  const managed = findManagedListItem(schema);

  if (managed !== undefined) {
    return `ManagedListOption<${renderItem(managed)}>`;
  }

  const list = findListItem(schema);

  return list === undefined ? undefined : `ListOption<${renderItem(list)}>`;
}

function withType(schema: JsonSchema, tsType: string): JsonSchema {
  const typed = { ...schema, tsType };

  return typed;
}

function allowUndefined(
  { entries }: ConfigSchema & ObjectConfigSchema,
  jsonSchema: JsonSchema,
): JsonSchema {
  const properties = mappedValues(
    jsonSchema.properties ?? {},
    (property, name): JsonSchema | boolean => {
      if (isBoolean(property) || entries[name]?.type !== "optional") {
        return property;
      }

      const { description, ...rest } = property;

      const wrapped: JsonSchema = {
        anyOf: [rest, withType(rest, "undefined")],
      };

      if (description !== undefined) {
        wrapped.description = description;
      }

      return wrapped;
    },
  );

  return { ...jsonSchema, properties };
}

function isObjectDefinition(definition: JsonSchema | boolean): boolean {
  return !isBoolean(definition) && definition.type === "object";
}

function placeObjectsLast(jsonSchema: JsonSchema): JsonSchema {
  const anyOf = [
    ...(jsonSchema.anyOf ?? []).filter((member) => !isObjectDefinition(member)),
    ...(jsonSchema.anyOf ?? []).filter((member) => isObjectDefinition(member)),
  ];

  return { ...jsonSchema, anyOf };
}

function descriptionOf(schema: ConfigSchema): string | undefined {
  return getDescription(
    "wrapped" in schema && isConfigSchema(schema.wrapped)
      ? schema.wrapped
      : schema,
  );
}

function createOverride(names: ReadonlyMap<ConfigSchema, string>) {
  return ({ valibotSchema, jsonSchema }: OverrideSchemaContext) => {
    const target = getLazyConfigSchema(valibotSchema);

    const referenced = names.get(
      target === undefined ? valibotSchema : getCoreConfigSchema(target),
    );

    if (referenced !== undefined) {
      return withType({ type: "object" }, referenced);
    }

    return overrideSchema({ valibotSchema, jsonSchema });
  };
}

function overrideSchema({
  valibotSchema,
  jsonSchema,
}: Pick<OverrideSchemaContext, "valibotSchema" | "jsonSchema">) {
  const tsType = resolveType(valibotSchema);

  if (tsType !== undefined) {
    return withType(jsonSchema, tsType);
  }

  if (valibotSchema.type === "union" && jsonSchema.anyOf !== undefined) {
    return placeObjectsLast(jsonSchema);
  }

  if (valibotSchema.type === "strict_object") {
    return allowUndefined(
      valibotSchema as ConfigSchema & ObjectConfigSchema,
      jsonSchema,
    );
  }
}

function resolveNamedReferences(value: unknown): unknown {
  if (isArray(value)) {
    return map(value, resolveNamedReferences);
  }

  if (!isObject(value)) {
    return value;
  }

  const reference = "$ref" in value ? value.$ref : undefined;

  if (isString(reference) && reference.startsWith(namedReference)) {
    return withType({ type: "object" }, reference.slice(namedReference.length));
  }

  return mappedValues(value, resolveNamedReferences);
}

async function render(
  core: ConfigSchema,
  name: string,
  names: ReadonlyMap<ConfigSchema, string>,
  description: string | undefined,
): Promise<string> {
  const jsonSchema = toJsonSchema(
    {
      ...core,
    },
    {
      errorMode: "ignore",
      typeMode: "input",
      overrideSchema: createOverride(names),
      overrideRef({ valibotSchema }) {
        const referenced = names.get(getCoreConfigSchema(valibotSchema));

        return referenced === undefined
          ? undefined
          : `${namedReference}${referenced}`;
      },
    },
  );

  if (description !== undefined) {
    jsonSchema.description = description;
  }

  delete jsonSchema.$defs;

  // @debt the draft 07 JSON schema of valibot is asserted to the draft 04 type of json-schema-to-typescript-lite, which only differs by numeric exclusive bounds that the config sections do not use
  const document = resolveNamedReferences(jsonSchema) as Parameters<
    typeof compile
  >[0];

  const declarations = await compile(document, name, {
    additionalProperties: false,
    unknownAny: true,
  });

  return declarations.replaceAll("}\n/**", "}\n\n/**");
}

export async function generateConfigTypes(
  config: LoadedConfig,
  modules: ReadonlyMap<File, Readonly<Record<string, unknown>>>,
) {
  const sections = await composeInputSchemas(config);

  const root = strictObject(sections);
  const inputs = collectConfigInputs(modules, sections, root);

  const names = new Map(
    map([...inputs], ([core, { name }]) => [core, name] as const),
  );

  const sources = new Map(externalTypes);

  for (const { name, domain } of inputs.values()) {
    sources.set(name, { domain, specifier: undefined });
  }

  const files = [
    ...map([...inputs], ([core, { name, domain, declaration }]) => {
      return {
        name,
        domain,
        file: `src/${domain}/types/${name}.ts`,
        core,
        description: descriptionOf(declaration.schema),
        trailer: [],
      };
    }),
    {
      name: composedName,
      domain: composedDomain,
      file: composedFile,
      core: root,
      description: undefined,
      trailer: [
        "declare global {",
        `  interface EngrenageConfigInput extends ${composedName} {}`,
        "}",
        "",
        "export type ConfigInput = EngrenageConfigInput;",
        "",
      ],
    },
  ];

  for (const { name, domain, file, core, description, trailer } of files) {
    const declarations = await render(core, name, names, description);

    const filesystem = config.context.filesystem;

    await filesystem.write(
      file,
      [
        generatedHeader,
        ...findConfigTypeImports(declarations, name, domain, sources),
        "",
        declarations,
        ...trailer,
      ].join("\n"),
    );
  }
}
