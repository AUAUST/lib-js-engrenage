const composedDomain: Directory = "workflows/config";

const composedName = "ConfigInput";

const generatedHeader =
  "// Generated by `pnpm support codegen config`. Do not edit.\n";

interface TypeSource {
  domain: Directory | undefined;
  specifier: string | undefined;
}

const externalTypes = new Map<string, TypeSource>([
  ["ListOption", { domain: "foundation/options", specifier: undefined }],
  ["ManagedListOption", { domain: "foundation/options", specifier: undefined }],
  ["GlobalsFactory", { domain: "project/config", specifier: undefined }],
  [
    "EffectModuleResolver",
    { domain: "project/structure", specifier: undefined },
  ],
  ["Glob", { domain: undefined, specifier: "#types/Glob" }],
  ["Globs", { domain: undefined, specifier: "#types/Globs" }],
]);

type AnySchema = BaseSchema<unknown, unknown, BaseIssue<unknown>>;

interface Declaration {
  schema: AnySchema;
  entries: Readonly<Record<string, unknown>>;
}

interface DeclaredInput {
  name: string;
  domain: Directory;
  declaration: Declaration;
}

type SchemaModules = ReadonlyMap<File, Readonly<Record<string, unknown>>>;

interface UnionSchema {
  type: "union";
  options: readonly AnySchema[];
}

interface ObjectSchema {
  type: "strict_object";
  entries: Readonly<Record<string, AnySchema>>;
}

const adjustmentKeys = ["append", "exclude", "prepend"];

function isUnion(schema: AnySchema): schema is AnySchema & UnionSchema {
  return schema.type === "union";
}

function isAdjustment(schema: AnySchema): boolean {
  const { entries } = schema as AnySchema & Partial<ObjectSchema>;

  return (
    schema.type === "strict_object" &&
    entries !== undefined &&
    keys(entries).sort().join() === adjustmentKeys.join()
  );
}

function findListItem(schema: AnySchema): AnySchema | undefined {
  if (!isUnion(schema) || schema.options.length !== 2) {
    return;
  }

  const [items, adjustment] = schema.options;

  if (!isAdjustment(adjustment) || !isUnion(items)) {
    return;
  }

  return items.options[0];
}

function findManagedListItem(schema: AnySchema): AnySchema | undefined {
  if (!isUnion(schema) || schema.options.length !== 2) {
    return;
  }

  const [list, flag] = schema.options;

  return flag.type === "boolean" ? findListItem(list) : undefined;
}

function renderItem(schema: AnySchema): string {
  const { type, enum: values } = toJsonSchema(schema, {
    errorMode: "throw",
  }) as { type?: string; enum?: readonly string[] };

  if (type === "string" && values === undefined) {
    return "string";
  }

  if (values !== undefined) {
    return values.map((value) => JSON.stringify(value)).join(" | ");
  }

  throw new Error(
    `The list item of type ${schema.type} has no TypeScript form`,
  );
}

function optionsOf(schema: object): unknown {
  return "options" in schema ? schema.options : undefined;
}

const readonlyListTypes = new Map<unknown, string>([
  [optionsOf(globsSchema), "Glob | Globs"],
]);

function resolveType(schema: AnySchema): string | undefined {
  if (schema === effectModuleResolverSchema) {
    return "EffectModuleResolver";
  }

  if (schema.type === "custom") {
    return "GlobalsFactory";
  }

  const readonlyList = readonlyListTypes.get(optionsOf(schema));

  if (readonlyList !== undefined) {
    return readonlyList;
  }

  const managed = findManagedListItem(schema);

  if (managed !== undefined) {
    return `ManagedListOption<${renderItem(managed)}>`;
  }

  const list = findListItem(schema);

  return list === undefined ? undefined : `ListOption<${renderItem(list)}>`;
}

function withType(schema: JsonSchema, tsType: string): JsonSchema {
  const typed = { ...schema, tsType };

  return typed;
}

function allowUndefined(
  { entries }: AnySchema & ObjectSchema,
  jsonSchema: JsonSchema,
): JsonSchema {
  const properties = mappedValues(
    jsonSchema.properties ?? {},
    (property, name): JsonSchema | boolean => {
      if (isBoolean(property) || entries[name]?.type !== "optional") {
        return property;
      }

      const { description, ...rest } = property;

      const wrapped: JsonSchema = {
        anyOf: [rest, withType(rest, "undefined")],
      };

      if (description !== undefined) {
        wrapped.description = description;
      }

      return wrapped;
    },
  );

  return { ...jsonSchema, properties };
}

function isObjectDefinition(definition: JsonSchema | boolean): boolean {
  return !isBoolean(definition) && definition.type === "object";
}

function placeObjectsLast(jsonSchema: JsonSchema): JsonSchema {
  const anyOf = [
    ...(jsonSchema.anyOf ?? []).filter((member) => !isObjectDefinition(member)),
    ...(jsonSchema.anyOf ?? []).filter((member) => isObjectDefinition(member)),
  ];

  return { ...jsonSchema, anyOf };
}

function isSchema(value: unknown): value is AnySchema {
  return isObject(value) && "kind" in value && value.kind === "schema";
}

function isDeclaration(value: unknown): value is Declaration {
  return (
    isObject(value) &&
    "schema" in value &&
    isSchema(value.schema) &&
    "entries" in value &&
    isObject(value.entries)
  );
}

function isObjectSchema(schema: AnySchema): schema is AnySchema & ObjectSchema {
  return schema.type === "strict_object";
}

function coreOf(schema: AnySchema): AnySchema {
  if ("pipe" in schema && isArray(schema.pipe)) {
    return coreOf(schema.pipe[0]);
  }

  if ("wrapped" in schema && isSchema(schema.wrapped)) {
    return coreOf(schema.wrapped);
  }

  if (isUnion(schema) && schema.options.length === 2) {
    const [flag, core] = schema.options;

    if (flag.type === "literal") {
      return coreOf(core);
    }
  }

  return schema;
}

function descriptionOf(schema: AnySchema): string | undefined {
  return getDescription(
    "wrapped" in schema && isSchema(schema.wrapped) ? schema.wrapped : schema,
  );
}

function lazyTargetOf(schema: AnySchema): AnySchema | undefined {
  if (
    schema.type !== "lazy" ||
    !("getter" in schema) ||
    !isFunction(schema.getter)
  ) {
    return;
  }

  const target: unknown = schema.getter(undefined);

  return isSchema(target) ? target : undefined;
}

function childrenOf(schema: AnySchema): AnySchema[] {
  if ("pipe" in schema && isArray(schema.pipe)) {
    return [schema.pipe[0]];
  }

  if (isObjectSchema(schema)) {
    return values(schema.entries);
  }

  const target = lazyTargetOf(schema);

  if (target !== undefined) {
    return [target];
  }

  return ["wrapped", "item", "key", "value"].flatMap((property) => {
    const child = (schema as unknown as Record<string, unknown>)[property];

    return isSchema(child) ? [child] : [];
  });
}

function countObjects(root: AnySchema): Map<AnySchema, number> {
  const counts = new Map<AnySchema, number>();

  function visit(schema: AnySchema) {
    const members =
      isUnion(schema) && !("pipe" in schema) ? schema.options : [];

    if (isObjectSchema(schema) && !("pipe" in schema)) {
      const seen = counts.has(schema);

      counts.set(schema, (counts.get(schema) ?? 0) + 1);

      if (seen) {
        return;
      }
    }

    for (const child of [...childrenOf(schema), ...members]) {
      visit(child);
    }
  }

  visit(root);

  return counts;
}

function collectInputs(modules: SchemaModules): Map<AnySchema, DeclaredInput> {
  const inputs = new Map<AnySchema, DeclaredInput>();

  for (const [file, exported] of modules) {
    const domain = file.slice("src/".length, file.indexOf("/config/schemas/"));

    for (const [exportName, value] of entries(exported)) {
      if (!isDeclaration(value) || !isObjectSchema(coreOf(value.schema))) {
        continue;
      }

      inputs.set(coreOf(value.schema), {
        name: `${toPascalCase(exportName.replace(/Schema$/, ""))}Input`,
        domain,
        declaration: value,
      });
    }
  }

  return inputs;
}

function selectInputs(
  declared: ReadonlyMap<AnySchema, DeclaredInput>,
): Map<AnySchema, DeclaredInput> {
  const root = coreOf(configSchema);
  const counts = countObjects(configSchema);

  const selected = new Map<AnySchema, DeclaredInput>();

  const wanted = [
    ...values(configDeclaration.entries).map((section) =>
      coreOf(section.schema),
    ),
    ...[...counts].filter(([, count]) => count > 1).map(([core]) => core),
  ];

  for (const core of wanted) {
    const input = declared.get(core);

    if (core === root || !isObjectSchema(core) || isAdjustment(core)) {
      continue;
    }

    if (input === undefined) {
      throw new Error(
        "A config schema used more than once has no exported declaration to name its interface",
      );
    }

    selected.set(core, input);
  }

  return selected;
}

function createOverride(names: ReadonlyMap<AnySchema, string>) {
  return ({ valibotSchema, jsonSchema }: OverrideSchemaContext) => {
    const target = lazyTargetOf(valibotSchema);

    const referenced = names.get(
      target === undefined ? valibotSchema : coreOf(target),
    );

    if (referenced !== undefined) {
      return withType({ type: "object" }, referenced);
    }

    return overrideSchema({ valibotSchema, jsonSchema });
  };
}

function overrideSchema({
  valibotSchema,
  jsonSchema,
}: Pick<OverrideSchemaContext, "valibotSchema" | "jsonSchema">) {
  const tsType = resolveType(valibotSchema);

  if (tsType !== undefined) {
    return withType(jsonSchema, tsType);
  }

  if (valibotSchema.type === "union" && jsonSchema.anyOf !== undefined) {
    return placeObjectsLast(jsonSchema);
  }

  if (valibotSchema.type === "strict_object") {
    return allowUndefined(
      valibotSchema as AnySchema & ObjectSchema,
      jsonSchema,
    );
  }
}

async function render(
  core: AnySchema,
  name: string,
  names: ReadonlyMap<AnySchema, string>,
  description: string | undefined,
): Promise<string> {
  const jsonSchema = toJsonSchema(
    {
      ...core,
    },
    {
      errorMode: "ignore",
      typeMode: "input",
      overrideSchema: createOverride(names),
    },
  );

  if (description !== undefined) {
    jsonSchema.description = description;
  }

  delete jsonSchema.$defs;

  // @debt the draft 07 JSON schema of valibot is asserted to the draft 04 type of json-schema-to-typescript-lite, which only differs by numeric exclusive bounds that configSchema does not use
  const document = jsonSchema as Parameters<typeof compile>[0];

  const declarations = await compile(document, name, {
    additionalProperties: false,
    unknownAny: true,
  });

  return declarations.replaceAll("}\n/**", "}\n\n/**");
}

function findImports(
  declarations: string,
  name: string,
  domain: Directory,
  sources: ReadonlyMap<string, TypeSource>,
): string[] {
  const code = declarations.replaceAll(/\/\*[\s\S]*?\*\//g, "");

  const specifiers = new Map<string, string[]>();

  for (const [used, source] of sources) {
    if (used === name || !new RegExp(String.raw`\b${used}\b`).test(code)) {
      continue;
    }

    const specifier =
      source.specifier ??
      (source.domain === domain
        ? `#${source.domain}/types/${used}`
        : `#${source.domain}/index`);

    specifiers.set(specifier, [...(specifiers.get(specifier) ?? []), used]);
  }

  return map(
    sort([...specifiers.keys()]),
    (specifier) =>
      `import type { ${sort(specifiers.get(specifier) ?? []).join(", ")} } from "${specifier}";`,
  );
}

export async function generateConfigTypes(
  config: ConfigContext,
  modules: SchemaModules,
) {
  const inputs = selectInputs(collectInputs(modules));

  const names = new Map(
    map([...inputs], ([core, { name }]) => [core, name] as const),
  );

  const sources = new Map(externalTypes);

  for (const { name, domain } of inputs.values()) {
    sources.set(name, { domain, specifier: undefined });
  }

  const files = [
    ...map([...inputs], ([core, { name, domain, declaration }]) => {
      return {
        name,
        domain,
        core,
        description: descriptionOf(declaration.schema),
      };
    }),
    {
      name: composedName,
      domain: composedDomain,
      core: coreOf(configSchema),
      description: undefined,
    },
  ];

  for (const { name, domain, core, description } of files) {
    const declarations = await render(core, name, names, description);

    const filesystem = await config.get("filesystem");

    filesystem.write(
      `src/${domain}/types/${name}.ts`,
      [
        generatedHeader,
        ...findImports(declarations, name, domain, sources),
        "",
        declarations,
      ].join("\n"),
    );
  }
}
