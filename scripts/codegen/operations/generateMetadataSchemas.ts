import { toJsonSchema } from "@valibot/to-json-schema";
import { optional, strictObject, type GenericSchema } from "valibot";

import { keys, mapValues, omit } from "@auaust/toolkit/object";

import {
  domainMetadataSchema,
  environmentMetadataSchema,
  namespaceMetadataSchema,
} from "#batiment/environments/index";
import { workspaceMetadataSchema } from "#batiment/scopes/index";
import { workspaceSchema } from "#project/workspaces/index";
import type { LoadedConfig } from "#project/config/index";

const comment = "Generated by `pnpm support codegen schemas`. Do not edit.";

function createWorkspaceFileSchema(): GenericSchema {
  const structural = workspaceMetadataSchema.entries;

  const remainder = omit(workspaceSchema.entries, ...keys(structural));

  return strictObject({
    ...mapValues(structural, ({ schema }) => schema),
    ...mapValues(remainder, ({ schema }) => optional(schema)),
  });
}

const schemas = [
  ["data/schemas/namespace.schema.json", namespaceMetadataSchema],
  ["data/schemas/domain.schema.json", domainMetadataSchema],
  ["data/schemas/environment.schema.json", environmentMetadataSchema],
  ["data/schemas/workspace.schema.json", createWorkspaceFileSchema()],
] as const;

export async function generateMetadataSchemas(
  config: LoadedConfig,
): Promise<void> {
  const filesystem = config.context.filesystem;

  for (const [file, schema] of schemas) {
    const document = { $comment: comment, ...toJsonSchema(schema) };

    await filesystem.write(file, `${JSON.stringify(document, null, 2)}\n`);
  }
}
