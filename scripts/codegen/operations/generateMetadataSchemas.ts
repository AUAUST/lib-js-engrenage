import { toJsonSchema } from "@valibot/to-json-schema";

import {
  domainMetadataSchema,
  namespaceMetadataSchema,
} from "#project/environments/index";
import type { LoadedConfig } from "#project/config/index";

const comment = "Generated by `pnpm support codegen schemas`. Do not edit.";

const schemas = [
  ["data/schemas/namespace.schema.json", namespaceMetadataSchema],
  ["data/schemas/domain.schema.json", domainMetadataSchema],
] as const;

export async function generateMetadataSchemas(
  config: LoadedConfig,
): Promise<void> {
  const filesystem = config.context.filesystem;

  for (const [file, schema] of schemas) {
    const document = { $comment: comment, ...toJsonSchema(schema) };

    await filesystem.write(file, `${JSON.stringify(document, null, 2)}\n`);
  }
}
