import { glob, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

import { flatConfigsToPlugins, pluginsToRulesDTS } from "eslint-typegen/core";
import { builtinRules } from "eslint/use-at-your-own-risk";
import { format, resolveConfig } from "prettier";

import { map, sort } from "@auaust/primitive-kit/arrays";
import { toPascalCase } from "@auaust/primitive-kit/strings";
import { mappedValues } from "@auaust/toolkit/mappedValues";
import { entries, record } from "@auaust/toolkit/object";

import { pathExists, resolve, toPosixPath } from "#foundation/filesystem/index";
import { rolesPluginName } from "#tools/eslint/constants";
import {
  createEslintConfig,
  normalizeRuleSchema,
  type Plugin,
} from "#tools/eslint/index";
import type { LoadedConfig } from "#project/config/index";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";
import type { Files } from "#types/Files";

const ruleSourcesDirectory: Directory = "src/tools/eslint/types/rules";

const rulesFile: File = "src/tools/eslint/types/Rules.ts";

const generatedHeader =
  "// Generated by `pnpm support codegen rules`. Do not edit.\n";

const ruleImport = 'import type { Rule } from "#tools/eslint/types/Rule";';

interface RuleSource {
  name: string;
  prefix: string;
  plugin: Plugin;
}

async function readRuleSources(config: LoadedConfig): Promise<RuleSource[]> {
  const configuredPlugins = await flatConfigsToPlugins(
    await createEslintConfig(config),
  );

  const shippedPlugins = entries(configuredPlugins).filter(([prefix]) => {
    return prefix !== rolesPluginName;
  });

  const pluginSources = map(shippedPlugins, ([prefix, plugin]) => {
    return {
      name: `${toPascalCase(prefix)}Rules`,
      prefix,
      plugin,
    };
  });

  return [
    {
      name: "CoreRules",
      prefix: "",
      plugin: {
        rules: record(builtinRules),
      },
    },
    ...pluginSources,
  ];
}

function normalizePluginSchemas(plugin: Plugin): Plugin {
  const rules = mappedValues(plugin.rules ?? {}, (rule) => {
    return {
      ...rule,
      meta: {
        ...rule.meta,
        schema: normalizeRuleSchema(rule.meta?.schema),
      },
    };
  });

  return {
    rules,
  };
}

async function createSourceModule({
  name,
  prefix,
  plugin,
}: RuleSource): Promise<string> {
  const declarations = await pluginsToRulesDTS(
    {
      [prefix]: normalizePluginSchemas(plugin),
    },
    {
      exportTypeName: name,
      includeAugmentation: false,
      includeIgnoreComments: false,
      includeTypeImports: false,
    },
  );

  return [
    generatedHeader,
    ruleImport,
    declarations.replaceAll("Linter.RuleEntry<", "Rule<"),
  ].join("\n");
}

function createRulesModule(sources: RuleSource[]): string {
  const imports = map(sources, ({ name }) => {
    return `import type { ${name} } from "#tools/eslint/types/rules/${name}";`;
  });

  const names = map(sources, ({ name }) => name);

  return [
    generatedHeader,
    ...imports,
    ruleImport,
    "",
    `export interface Rules extends Partial<Record<string, Rule>>, ${names.join(", ")} {}`,
  ].join("\n");
}

async function formatModule(path: string, content: string): Promise<string> {
  const options = await resolveConfig(path);

  return format(content, {
    ...options,
    filepath: path,
  });
}

export async function generateRuleTypes({
  config,
  check = false,
}: {
  config: LoadedConfig;
  check?: boolean;
}): Promise<Files> {
  const rootPath = config.context.root;

  const sources = await readRuleSources(config);

  const modules = new Map<File, string>([
    [rulesFile, createRulesModule(sources)],
  ]);

  for (const source of sources) {
    modules.set(
      `${ruleSourcesDirectory}/${source.name}.ts`,
      await createSourceModule(source),
    );
  }

  const existingFiles = await Array.fromAsync(
    glob(`${ruleSourcesDirectory}/*.ts`, {
      cwd: rootPath,
    }),
  );

  const staleFiles = map(existingFiles, toPosixPath).filter((file) => {
    return !modules.has(file);
  });

  const outdated: File[] = [...staleFiles];

  for (const [file, content] of modules) {
    const path = resolve(rootPath, file);

    const formatted = await formatModule(path, content);

    if (
      (await pathExists(path)) &&
      (await readFile(path, "utf-8")) === formatted
    ) {
      continue;
    }

    outdated.push(file);

    if (check) {
      continue;
    }

    await mkdir(dirname(path), {
      recursive: true,
    });

    await writeFile(path, formatted);
  }

  if (!check) {
    await Promise.all(staleFiles.map((file) => rm(resolve(rootPath, file))));
  }

  return sort(outdated);
}
