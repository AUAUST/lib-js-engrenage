import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join as joinPath } from "node:path";

import {
  createSourceFile,
  flattenDiagnosticMessageText,
  ScriptTarget,
  version,
  type SourceFile,
} from "typescript";

import {
  filter,
  filterMap,
  join,
  map,
  sort,
} from "@auaust/primitive-kit/arrays";
import { entries, keys } from "@auaust/toolkit/object";

import { resolve } from "#foundation/filesystem/index";
import { apiGroupRoots, apiLibraryGroups } from "#project/baseline/constants";
import { includesEsLibrary, listEsSelections } from "#project/baseline/index";
import { createApiDeclarationCollector } from "#scripts/codegen/utils/createApiDeclarationCollector";
import { createLibraryCompiler, formatModule } from "#tools/typescript/index";
import type { LoadedConfig } from "#project/config/index";
import type { Directory } from "#types/Directory";
import type { File } from "#types/File";

const apisDirectory = "data/apis";

const sharedFile: File = `${apisDirectory}/shared/common.d.ts`;

const sharedReference = "shared/common.d.ts";

function readNotice(text: string): string {
  const end = text.indexOf("*/");

  return text.slice(0, end + 2);
}

function readLibraryText(name: string, libraries: Directory): Promise<string> {
  return readFile(joinPath(libraries, name), "utf-8");
}

function createModule({
  notice,
  origin,
  reference,
  body,
}: {
  notice: string;
  origin: string;
  reference: boolean;
  body: readonly string[];
}): string {
  const header = [
    notice,
    `// Generated by \`pnpm support codegen apis\` from the ${origin} of TypeScript ${version}. Do not edit.`,
  ];

  return [
    ...header,
    ...(reference ? [`/// <reference path="${sharedReference}" />`] : []),
    "",
    body.join("\n\n"),
    "",
  ].join("\n");
}

function pickStatements(
  source: SourceFile,
  positions: readonly number[],
): string[] {
  return map(sort([...positions]), (position) => {
    return source.statements[position]?.getFullText(source).trim() ?? "";
  });
}

function readLibraryBody(text: string): string {
  return text
    .slice(readNotice(text).length)
    .replaceAll(/^\/\/\/ <reference lib="[^"]*" \/>\r?\n/gm, "")
    .trim();
}

function assertCompilesWithSelections(
  group: string,
  groupLibrary: string | undefined,
  modules: ReadonlyMap<File, string>,
  selections: readonly { from: string; lib: readonly string[] }[],
  compile: ReturnType<typeof createLibraryCompiler>["compile"],
) {
  for (const { from, lib } of selections) {
    if (groupLibrary !== undefined && includesEsLibrary(lib, groupLibrary)) {
      continue;
    }

    const diagnostic = compile({
      lib,
      trusted: lib,
      sources: modules,
      entry: `${apisDirectory}/${group}.d.ts`,
    });

    if (diagnostic !== undefined) {
      throw new Error(
        `The "${group}" API group does not compile with the ES libs selected from ${from} (${join(lib, ", ")}): ${flattenDiagnosticMessageText(diagnostic.messageText, "\n")}`,
      );
    }
  }
}

export async function generateApiDeclarations(
  config: LoadedConfig,
  groups: readonly string[] = [],
  {
    libraryGroups = apiLibraryGroups,
    libraries = dirname(
      createRequire(import.meta.url).resolve("typescript/lib/lib.dom.d.ts"),
    ),
    selections = listEsSelections(),
  }: {
    libraryGroups?: Readonly<Record<string, string>>;
    libraries?: Directory;
    selections?: readonly { from: string; lib: readonly string[] }[];
  } = {},
) {
  const unknown = filter(
    groups,
    (group) => !(group in apiGroupRoots || group in libraryGroups),
  );

  if (unknown.length > 0) {
    throw new Error(
      `Unknown API groups: ${join(unknown, ", ")}. Available groups: ${join([...keys(apiGroupRoots), ...keys(libraryGroups)], ", ")}`,
    );
  }

  const libraryPath = createRequire(import.meta.url).resolve(
    "typescript/lib/lib.dom.d.ts",
  );

  const text = await readFile(libraryPath, "utf-8");

  const source = createSourceFile(
    "lib.dom.d.ts",
    text,
    ScriptTarget.ESNext,
    true,
  );

  const { collectClosure } = createApiDeclarationCollector(source);

  const closures = new Map(
    map(entries(apiGroupRoots), ([group, roots]) => {
      return [group, collectClosure(roots)] as const;
    }),
  );

  const counts = new Map<number, number>();

  for (const closure of closures.values()) {
    for (const position of closure) {
      counts.set(position, (counts.get(position) ?? 0) + 1);
    }
  }

  const shared = new Set(
    filterMap(
      [...counts],
      ([, count]) => count > 1,
      ([position]) => position,
    ),
  );

  const notice = readNotice(text);

  const modules = new Map<File, string>([
    [
      sharedFile,
      createModule({
        notice,
        origin: "lib.dom.d.ts",
        reference: false,
        body: pickStatements(source, [...shared]),
      }),
    ],
  ]);

  for (const [group, closure] of closures) {
    const own = [...closure].filter((position) => !shared.has(position));

    modules.set(
      `${apisDirectory}/${group}.d.ts`,
      createModule({
        notice,
        origin: "lib.dom.d.ts",
        reference: own.length < closure.size,
        body: pickStatements(source, own),
      }),
    );
  }

  for (const [group, name] of entries(libraryGroups)) {
    const text = await readLibraryText(name, libraries);

    modules.set(
      `${apisDirectory}/${group}.d.ts`,
      createModule({
        notice: readNotice(text),
        origin: name,
        reference: false,
        body: [readLibraryBody(text)],
      }),
    );
  }

  const { compile } = createLibraryCompiler();

  for (const group of [...keys(apiGroupRoots), ...keys(libraryGroups)]) {
    if (groups.length > 0 && !groups.includes(group)) {
      continue;
    }

    const name = libraryGroups[group];

    assertCompilesWithSelections(
      group,
      // @debt the lib name is derived from the lib.<name>.d.ts file-name convention instead of being declared next to the group
      name === undefined ? undefined : name.slice(4, -".d.ts".length),
      modules,
      selections,
      compile,
    );
  }

  const filesystem = config.context.filesystem;
  const root = config.context.root;

  for (const [file, content] of modules) {
    const isRequested =
      file === sharedFile ||
      groups.length === 0 ||
      groups.some((group) => file === `${apisDirectory}/${group}.d.ts`);

    if (isRequested) {
      await filesystem.write(
        file,
        await formatModule(resolve(root, file), content),
      );
    }
  }
}
